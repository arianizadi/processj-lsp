interface Unfolded {
  wrappers: Wrapper[];
  /** Why a reference to a composition was not unfolded (the depth limit, or a composition that contains itself). */
  cut?: string;
  /** A composition, with its environment. */
  comp?: { expr: Ex; env: Env };
}

class ViewBuilder {
  private readonly nodes: NetNode[] = [];
  private readonly edges: NetEdge[] = [];
  private readonly channels: NetChannel[] = [];
  private readonly notes: string[] = [];
  private readonly leaves = new Map<string, LeafNode>();
  private leafCount = 0;
  private readonly maxDepth: number;
  private readonly maxLeaves: number;
  private readonly maxReplicated: number;
  private readonly uri: string;

  constructor(private readonly root: CspmRoot, readonly globals: Globals, private readonly options: CspmNetworkOptions) {
    this.maxDepth = options.maxDepth ?? 8;
    this.maxLeaves = options.maxLeaves ?? 160;
    this.maxReplicated = options.maxReplicated ?? 16;
    this.uri = options.uri;
  }

  build(): CspmView {
    this.globals.budget = Math.max(this.globals.budget, 200_000);
    const env = this.globals.env;
    const unfolded = this.unfold(this.root.expr, env, 0, new Set());
    let tree: TreeNode;
    if (unfolded.comp) {
      tree = this.comp(unfolded.comp.expr, unfolded.comp.env, [], 'n:root', unfolded.wrappers, 0, new Set(), true);
    } else {
      tree = this.leaf(this.root.expr, env, [], 'n:root', [], undefined, true);
    }
    const linker = new Linker(this, tree);
    const links = linker.run();
    this.draw(tree, links, linkerBlocked(linker.blocked));
    if (this.options.generated && this.edges.some((edge) => !edge.label && edge.kind === 'channel' && !edge.tags.includes('port'))) this.notes.push("The translator's own events (pj_fork_…, pj_join_…, pj_end) are drawn without labels: click an arrow for its events.");
    for (const wrapper of tree.wrappers) {
      if (wrapper.kind === 'rename') this.notes.push(`The renaming ${wrapper.text} around this network is ${wrapper.map ? 'applied to the events drawn' : 'not followed: its events are drawn as written'}.`);
    }
    const view: NetworkView = {
      id: this.root.id,
      kind: 'procedure',
      procedure: this.root.name,
      label: this.root.label,
      source: this.root.source,
      nodes: this.nodes,
      edges: this.edges,
      channels: this.channels,
      notes: [...new Set(this.notes)],
      instances: [],
      section: this.root.section === 'asserted' ? 'Asserted' : 'Defined',
      language: 'cspm',
    };
    return { root: this.root, view, tree, links, blocked: this.blockedDrawn, leaves: this.leaves };
  }

  note(text: string): void {
    this.notes.push(text);
  }

  text(span: Span): string {
    return spanText(this.options.text, span);
  }

  // -------------------------------------------------------------------------
  // Unfolding references to compositions
  // -------------------------------------------------------------------------

  /** Follow references, hiding, renaming and the like down to a composition, if there is one. */
  unfold(expr: Ex, env: Env, depth: number, seen: Set<string>): Unfolded {
    const wrappers: Wrapper[] = [];
    let current = expr;
    let at = env;
    for (let steps = 0; steps < 64; steps++) {
      switch (current.k) {
        case 'par':
        case 'apar':
        case 'link':
          return { wrappers, comp: { expr: current, env: at } };
        case 'op':
          if (current.op === '|||') return { wrappers, comp: { expr: current, env: at } };
          if (current.op === ';' || current.op === '[>' || current.op === '/\\') {
            // `P ; Q` with a network P: the network is drawn, what follows is a note.
            const inner = this.unfold(current.left, at, depth, seen);
            if (!inner.comp) return { wrappers: [] };
            wrappers.push({ kind: 'after', text: `${current.op} ${this.text(current.right.span)}` }, ...inner.wrappers);
            return { wrappers, comp: inner.comp };
          }
          return { wrappers: [] };
        case 'repl':
          if (current.op === '|||' || current.op === '[|' || current.op === '||') return { wrappers, comp: { expr: current, env: at } };
          return { wrappers: [] };
        case 'exception': {
          const inner = this.unfold(current.left, at, depth, seen);
          if (!inner.comp) return { wrappers: [] };
          wrappers.push({ kind: 'after', text: `[| ${this.text(current.set.span)} |> ${this.text(current.right.span)}` }, ...inner.wrappers);
          return { wrappers, comp: inner.comp };
        }
        case 'hide': {
          const set = toEvents(evaluate(current.set, at), this.globals);
          wrappers.push({ kind: 'hide', ...(set ? { set } : {}), text: this.text(current.set.span) });
          current = current.proc;
          continue;
        }
        case 'rename':
          wrappers.push({ kind: 'rename', text: `[[${current.pairs.map(([from, to]) => `${this.text(from.span)} <- ${this.text(to.span)}`).join(', ')}]]`, ...renameMap(current, at, this.globals) });
          current = current.proc;
          continue;
        case 'let':
          at = letEnv(current.decls, at);
          current = current.body;
          continue;
        case 'if': {
          const cond = evaluate(current.cond, at);
          if (cond.t !== 'bool') return { wrappers: [] };
          current = cond.v ? current.then : current.else;
          continue;
        }
        case 'name':
        case 'app': {
          if (current.k === 'app' && current.fn.k === 'name' && TRANSPARENT_FUNCTIONS.has(current.fn.name) && current.args.length === 1 && !this.globals.defs.has(current.fn.name)) {
            wrappers.push({ kind: 'function', name: current.fn.name });
            current = current.args[0];
            continue;
          }
          const value = evaluate(current, at);
          if (value.t !== 'proc' || !value.name) return { wrappers: [] };
          const deep = depth + wrappers.filter((w) => w.kind === 'call').length >= this.maxDepth;
          const again = seen.has(value.name) || wrappers.some((w) => w.kind === 'call' && w.name === value.name);
          if (deep || again) {
            // Said only when what is not unfolded is itself a composition: a process is a box either way.
            if (!composes(value.expr)) return { wrappers: [] };
            const cut = again ? `${value.name} is a composition that contains itself: it is drawn as one box here` : `${value.name} is a composition, not unfolded: the view stops ${this.maxDepth} references deep`;
            this.note(again ? `${value.name} contains itself as an operand: it is drawn once unfolded and, inside, as one box.` : `Compositions more than ${this.maxDepth} references deep are not unfolded: each is drawn as one box that says so (here ${value.name.replace(/\(.*$/, '')}(…), which keeps composing).`);
            return { wrappers: [], cut };
          }
          const base = value.name.replace(/\(.*$/, '');
          wrappers.push({ kind: 'call', name: value.name, label: this.callLabel(current, at), site: current.span, definition: this.globals.definitions.get(base)?.[0] });
          current = value.expr;
          at = value.env;
          continue;
        }
        default:
          return { wrappers: [] };
      }
    }
    return { wrappers: [] };
  }

  /** `PHIL(0)`, `COPY(left, mid)`: a reference with its arguments' values (as written when unknown). */
  callLabel(expr: Ex, env: Env): string {
    if (expr.k === 'name') return expr.name;
    if (expr.k === 'app') {
      const fn = expr.fn.k === 'name' ? expr.fn.name : this.text(expr.fn.span);
      const args = expr.args.map((arg) => {
        const value = evaluate(arg, env);
        return value.t === 'unknown' || value.t === 'proc' || value.t === 'fn' ? this.text(arg.span) : show(value);
      });
      return `${fn}(${args.join(', ')})`;
    }
    return this.text(expr.span);
  }

  /** An inline operand for its values: `pass.((i+1)%N) -> NODE(0)` with i = 0 is `pass.1 -> NODE(0)`. */
  termLabel(expr: Ex, env: Env, depth = 0): string {
    if (expr.k === 'name' || expr.k === 'app') return this.callLabel(expr, env);
    if (expr.k !== 'prefix' || depth > 3) return this.text(expr.span);
    const head = evaluate(expr.head, env);
    const known = (value: Value): boolean => value.t !== 'unknown' && value.t !== 'proc' && value.t !== 'fn';
    let event = known(head) ? show(head) : this.text(expr.head.span);
    const inner = env.child();
    for (const field of expr.fields) {
      if (field.kind === '?' || field.kind === '$') {
        event += `${field.kind}${this.text(field.expr.span)}`;
        // What an input binds is not known here.
        const bound = new Map<string, Value>();
        match(field.expr, { t: 'unknown', why: 'an input' }, this.globals, bound);
        for (const [name, value] of bound) inner.set(name, value);
        continue;
      }
      const value = evaluate(field.expr, env);
      event += `${field.kind === '!' ? '!' : '.'}${known(value) ? show(value) : this.text(field.expr.span)}`;
    }
    return `${event} -> ${this.termLabel(expr.body, inner, depth + 1)}`;
  }

  // -------------------------------------------------------------------------
  // The tree
  // -------------------------------------------------------------------------

  private comp(expr: Ex, env: Env, path: ProcessPath, id: string, wrappers: Wrapper[], depth: number, seen: Set<string>, isRoot = false): CompNode {
    const operands: Array<{ expr: Ex; env: Env; step: SpawnSite; alphabet?: Events; replicated?: { count?: number; text: string } }> = [];
    let op: CompNode['op'] = '[|';
    let operator = '';
    let sync: Events | undefined;
    let unknownSync: string | undefined;
    let shape: Shape | undefined;
    const site = { uri: this.uri, span: expr.span };
    const branch = (index: number): SpawnSite => ({ kind: 'branch', site, index });
    if (expr.k === 'par' || (expr.k === 'op' && expr.op === '|||')) {
      // A chain of the same operator with the same set is one composition of several operands.
      const same = (e: Ex): boolean => expr.k === 'par' ? e.k === 'par' && this.text(e.sync.span) === this.text(expr.sync.span) : e.k === 'op' && e.op === '|||';
      const flat: Ex[] = [];
      const collect = (e: Ex): Shape => {
        if (same(e) && (e.k === 'par' || e.k === 'op')) return [collect(e.left), collect(e.right)];
        flat.push(e);
        return flat.length - 1;
      };
      shape = collect(expr);
      flat.forEach((operand, i) => operands.push({ expr: operand, env, step: branch(i + 1) }));
      if (expr.k === 'par') {
        op = '[|';
        operator = `[| ${this.text(expr.sync.span)} |]`;
        const value = evaluate(expr.sync, env);
        sync = toEvents(value, this.globals);
        if (!sync) unknownSync = value.t === 'unknown' ? value.why : `${show(value)} is not a set of events`;
      } else {
        op = '|||';
        operator = '|||';
      }
    } else if (expr.k === 'apar') {
      op = '||';
      operator = `[ ${this.text(expr.alphaLeft.span)} || ${this.text(expr.alphaRight.span)} ]`;
      const alpha = (e: Ex): Events | undefined => {
        const value = evaluate(e, env);
        const events = toEvents(value, this.globals);
        if (!events) unknownSync = value.t === 'unknown' ? value.why : `${show(value)} is not a set of events`;
        return events;
      };
      operands.push({ expr: expr.left, env, step: branch(1), alphabet: alpha(expr.alphaLeft) }, { expr: expr.right, env, step: branch(2), alphabet: alpha(expr.alphaRight) });
    } else if (expr.k === 'link') {
      op = 'link';
      operator = `[ ${expr.pairs.map(([a, b]) => `${this.text(a.span)} <-> ${this.text(b.span)}`).join(', ')} ]`;
      unknownSync = 'a linked parallel renames the channels it links';
      this.note(`The linked parallel ${operator} is drawn with its two operands, but not the links: it renames the channels it joins, which the graph does not follow.`);
      operands.push({ expr: expr.left, env, step: branch(1) }, { expr: expr.right, env, step: branch(2) });
    } else if (expr.k === 'repl') {
      op = expr.op === '|||' ? '|||' : expr.op === '||' ? '||' : '[|';
      const stmts = expr.stmts.map((stmt) => this.text(stmt.span)).join(', ');
      operator = expr.op === '[|' ? `[| ${this.text(expr.sync!.span)} |] ${stmts}` : `${expr.op} ${stmts}`;
      if (expr.op === '[|') {
        const value = evaluate(expr.sync!, env);
        sync = toEvents(value, this.globals);
        if (!sync) unknownSync = value.t === 'unknown' ? value.why : `${show(value)} is not a set of events`;
      }
      const bindings: Env[] = [];
      const ok = comprehend(expr.stmts, env, (inner) => {
        bindings.push(inner);
        return bindings.length <= this.maxReplicated;
      });
      const alphaOf = (inner: Env): Events | undefined => {
        if (!expr.alpha) return undefined;
        const value = evaluate(expr.alpha, inner);
        const events = toEvents(value, this.globals);
        if (!events) unknownSync = value.t === 'unknown' ? value.why : `${show(value)} is not a set of events`;
        return events;
      };
      // How many members there are, when a finite set too large to draw one by one.
      let total: number | undefined = ok === true ? bindings.length : undefined;
      if (bindings.length > this.maxReplicated) {
        let count = 0;
        if (comprehend(expr.stmts, env, () => ++count <= 100_000) === true) total = count;
      }
      if (ok === true && bindings.length <= this.maxReplicated && bindings.length > 0) {
        bindings.forEach((inner, i) => operands.push({ expr: expr.body, env: inner, step: { kind: 'par-for', site, index: i + 1 }, alphabet: alphaOf(inner) }));
      } else {
        // Drawn once for every member, the bound names unknown.
        const unknownEnv = bindUnknown(expr.stmts, env, this.globals);
        const count = total;
        if (ok === true && bindings.length === 0) this.note(`${operator} has no members: it is SKIP.`);
        else this.note(`${operator} is drawn as one box standing for ${count !== undefined ? `its ${count} members` : `every member (${ok === true ? 'too many to draw' : ok})`}.`);
        if (count === undefined || count > 0) operands.push({ expr: expr.body, env: unknownEnv, step: { kind: 'par-for', site }, alphabet: alphaOf(unknownEnv), replicated: { ...(count !== undefined ? { count } : {}), text: count !== undefined ? `×${count}` : '×N' } });
      }
    }
    if (unknownSync && expr.k !== 'link') this.note(`The synchronisation of ${operator} could not be worked out (${unknownSync}): the events its operands share are not drawn there.`);
    const node: CompNode = { kind: 'comp', node: id, path, op, label: isRoot ? this.root.label : '', operator, children: [], ...(sync ? { sync } : {}), wrappers, span: expr.span, ...(unknownSync ? { unknownSync } : {}), ...(Array.isArray(shape) && operands.length > 2 ? { shape } : {}) };
    const alphabets: Array<Events | undefined> = [];
    for (const operand of operands) {
      const childPath = [...path, operand.step];
      if (this.leafCount >= this.maxLeaves) {
        this.note(`This view stops at ${this.maxLeaves} processes: deeper compositions are drawn as one box each.`);
      }
      const unfolded = this.leafCount < this.maxLeaves ? this.unfold(operand.expr, operand.env, depth + 1, seen) : { wrappers: [] };
      let child: TreeNode;
      if (unfolded.comp) {
        // The references passed through on the way to a nested composition are steps of its path.
        const calls = unfolded.wrappers.filter((wrapper): wrapper is Extract<Wrapper, { kind: 'call' }> => wrapper.kind === 'call');
        const nestedPath = [...childPath, ...calls.map((call): SpawnSite => ({ kind: 'call', site: { uri: this.uri, span: call.site } }))];
        const inner = new Set(seen);
        for (const call of calls) inner.add(call.name);
        child = this.comp(unfolded.comp.expr, unfolded.comp.env, nestedPath, `g${pathKey(nestedPath, this.uri)}`, unfolded.wrappers, depth + calls.length, inner);
        child.label = calls.length ? calls[0].label : '';
        if (operand.replicated) child.replicated = operand.replicated;
      } else {
        child = this.leaf(operand.expr, operand.env, childPath, `p${pathKey(childPath, this.uri)}`, unfolded.wrappers, operand.replicated);
        if (unfolded.cut) child.cut = unfolded.cut;
      }
      node.children.push(child);
      alphabets.push(operand.alphabet);
    }
    if (op === '||') node.alphabets = alphabets;
    return node;
  }

  private leaf(written: Ex, writtenEnv: Env, path: ProcessPath, id: string, wrappers: Wrapper[], replicated?: { count?: number; text: string }, isRoot = false): LeafNode {
    this.leafCount++;
    // What the operand is for these values: `if i == 0 then A else NODE(i)` with i = 2 is NODE(2).
    let expr = written;
    let env = writtenEnv;
    for (let guard = 0; guard < 16; guard++) {
      if (expr.k === 'if') {
        const cond = evaluate(expr.cond, env);
        if (cond.t !== 'bool') break;
        expr = cond.v ? expr.then : expr.else;
      } else if (expr.k === 'let') {
        env = letEnv(expr.decls, env);
        expr = expr.body;
      } else break;
    }
    const walk = new UseWalker(this.globals, this.options.text);
    walk.process(expr, env, false, 0);
    const reference = expr.k === 'name' || expr.k === 'app' ? (expr.k === 'name' ? expr.name : expr.fn.k === 'name' ? expr.fn.name : undefined) : undefined;
    const definition = reference && this.globals.definitions.has(reference) ? reference : undefined;
    const label = isRoot ? this.root.label : reference ? this.callLabel(expr, env) : this.termLabel(expr, env);
    // An inline operand of a replicated composition: which member it is.
    const bound = !reference && !isRoot ? [...env.locals()].filter(([, value]) => value.t !== 'proc' && value.t !== 'fn' && value.t !== 'unknown').map(([name, value]) => `${name} = ${show(value)}`) : [];
    // A generated model's definitions say which ProcessJ statement they stand for: `alt_deadlock.pj:22: branch 1 of the par`.
    const origin = this.options.generated && definition ? this.globals.definitions.get(definition)?.[0]?.comment?.match(/([\w.-]+\.pj):(\d+): ([^]*?)$/) : undefined;
    if (origin) bound.unshift(`line ${origin[2]}: ${origin[3]}`);
    const leaf: LeafNode = { kind: 'leaf', node: id, path, label, expr, env, wrappers, uses: walk.uses, ...(definition ? { definition } : {}), partial: walk.partial, hidden: walk.hidden, ...(replicated ? { replicated } : {}), ...(bound.length ? { bindings: bound.join(', ') } : {}) };
    this.leaves.set(id, leaf);
    return leaf;
  }

  // -------------------------------------------------------------------------
  // Drawing
  // -------------------------------------------------------------------------

  private blockedDrawn: Blocked[] = [];

  private draw(tree: TreeNode, links: Link[], blocked: Blocked[]): void {
    this.blockedDrawn = blocked;
    const names = new Map<string, number>();
    const unique = (label: string): string => {
      const count = (names.get(label) ?? 0) + 1;
      names.set(label, count);
      return count === 1 ? label : `${label} #${count}`;
    };
    const parents = new Map<string, string | undefined>();
    const visit = (node: TreeNode, parent: string | undefined): void => {
      parents.set(node.node, parent);
      if (node.kind === 'leaf') {
        this.nodes.push(this.leafNode(node, parent, unique(node.label)));
        return;
      }
      const call = node.wrappers.find((wrapper): wrapper is Extract<Wrapper, { kind: 'call' }> => wrapper.kind === 'call');
      const isRoot = node.path.length === 0;
      const label = isRoot ? this.root.label : node.label || node.operator;
      const facts = this.wrapperFacts(node.wrappers);
      if (node.unknownSync) facts.push(`its synchronisation could not be worked out: ${node.unknownSync}`);
      this.nodes.push({
        id: node.node,
        kind: 'group',
        ...(parent ? { parent } : {}),
        label: truncateLabel(label, 60),
        name: unique(label),
        detail: node.label || isRoot ? truncateLabel(node.operator, 50) : undefined,
        badge: badgeOf(node.op),
        source: { uri: this.uri, span: isRoot ? this.root.source.span : call?.site ?? node.span },
        confidence: node.unknownSync ? 'unknown' : 'exact',
        path: node.path,
        ...(call?.definition ? { procedure: call.definition.name.name, call: { procedure: call.definition.name.name, text: call.label, declaration: { uri: this.uri, span: call.definition.name.span }, params: call.definition.params.flat().map((param) => this.text(param.span)) } } : {}),
        ...(node.replicated ? { replicated: node.replicated } : {}),
        group: isRoot ? 'procedure' : call ? 'call' : 'par',
        facts,
        operations: [],
      });
      // A composition nested in another of the same kind without a name of its own (`(A [| X |] B) [| Y |] C`,
      // the chains a translator writes) is drawn in the same box: its operands are siblings there.
      const merged: string[] = [];
      const children = (of: CompNode): TreeNode[] => of.children.flatMap((child) => {
        if (child.kind === 'comp' && !child.replicated && !child.wrappers.length && child.op === of.op && (of.op === '[|' || of.op === '|||')) {
          merged.push(child.operator);
          return children(child);
        }
        return [child];
      });
      const drawn = children(node);
      if (merged.length) {
        const group = this.nodes.find((entry) => entry.id === node.node);
        group?.facts.push(`also composes, drawn in this box: ${[...new Set(merged)].slice(0, 4).join('; ')}${merged.length > 4 ? '; …' : ''}`);
      }
      for (const child of drawn) visit(child, node.node);
    };
    visit(tree, undefined);
    this.linkNodes(links, parents);
    this.blockedNodes(blocked, parents);
  }

  /** An event no partner ever offers: a dangling end at the operand that would perform it. */
  private blockedNodes(blocked: Blocked[], parents: Map<string, string | undefined>): void {
    const byId = new Map(this.nodes.map((node) => [node.id, node]));
    const seen = new Set<string>();
    blocked.forEach((entry, index) => {
      for (const user of entry.users) {
        const key = `${user}|${entry.key}`;
        const leaf = this.leaves.get(user);
        const node = byId.get(user);
        if (seen.has(key) || !leaf || !node) continue;
        seen.add(key);
        const id = `x${index}:${entry.key.replace(/[^A-Za-z0-9_.]/g, '_')}:${this.channels.length}`;
        const missing = entry.missing.map((other) => byId.get(other)?.name ?? other);
        const stub: NetNode = {
          id: `stub:${id}`,
          kind: 'stub',
          ...(parents.get(user) ? { parent: parents.get(user) } : {}),
          label: `never shared: ${entry.key}`,
          name: `no partner for ${entry.key}`,
          confidence: entry.proven ? 'exact' : 'unknown',
          stub: { side: 'no-reader', proven: entry.proven },
          channel: id,
          facts: [`${entry.operator} synchronises on ${entry.key}, but ${missing.length ? listOf(missing) : 'the other side'} never ${missing.length === 1 ? 'performs' : 'perform'} it: it can never happen`],
          operations: [],
        };
        const operations = leaf.uses.filter((use) => compatible(use, parseKey(entry.key))).map((use): NetOperation => ({ kind: 'sync', channel: id, at: { uri: this.uri, span: use.at }, confidence: entry.proven ? 'exact' : 'unknown' }));
        node.operations.push(...operations);
        this.nodes.push(stub);
        const edgeId = `e${this.edges.length}:${id}`;
        this.edges.push({ id: edgeId, kind: 'channel', from: user, to: stub.id, channel: id, label: entry.key, confidence: entry.proven ? 'exact' : 'unknown', role: 'dangling', tags: ['undirected'] });
        this.channels.push({ id, kind: 'channel', ref: { name: entry.key, kind: 'channel', owner: [] }, name: entry.key, type: '', shared: { read: false, write: false }, writers: [], readers: [], members: [{ node: user, confidence: 'exact', operations, tags: ['sync'] }], edges: [edgeId], stub: stub.id });
      }
    });
  }

  private wrapperFacts(wrappers: readonly Wrapper[]): string[] {
    const out: string[] = [];
    for (const wrapper of wrappers) {
      if (wrapper.kind === 'hide') out.push(`hides ${wrapper.text}`);
      else if (wrapper.kind === 'rename') out.push(`renamed ${wrapper.text}`);
      else if (wrapper.kind === 'after') out.push(`then ${wrapper.text}`);
      else if (wrapper.kind === 'function') out.push(`${wrapper.name}(...) around it (the same behaviour)`);
      else if (wrapper.kind === 'call') out.push(`unfolds ${wrapper.label}`);
    }
    return out;
  }

  private leafNode(leaf: LeafNode, parent: string | undefined, name: string): NetNode {
    const definition = leaf.definition ? this.globals.definitions.get(leaf.definition)?.[0] : undefined;
    const facts: string[] = [];
    if (definition?.comment) facts.push(definition.comment);
    facts.push(...this.wrapperFacts(leaf.wrappers));
    if (leaf.hidden.length) facts.push(`hides inside itself: ${[...new Set(leaf.hidden.map((use) => useText(use)))].slice(0, 6).join(', ')}`);
    if (leaf.cut) facts.push(leaf.cut);
    for (const reason of [...new Set(leaf.partial)].slice(0, 3)) facts.push(`not every event it performs could be worked out: ${reason}`);
    return {
      id: leaf.node,
      kind: 'process',
      ...(parent ? { parent } : {}),
      label: truncateLabel(leaf.label, 44),
      name,
      source: { uri: this.uri, span: leaf.expr.span },
      confidence: leaf.partial.length ? 'conditional' : 'exact',
      path: leaf.path,
      ...(definition ? { procedure: definition.name.name, call: { procedure: definition.name.name, text: leaf.label, declaration: { uri: this.uri, span: definition.name.span }, params: definition.params.flat().map((param) => this.text(param.span)) } } : {}),
      ...(leaf.replicated ? { replicated: leaf.replicated } : {}),
      facts,
      operations: [],
    };
  }

  /** Channels, edges, hubs and ports for the links; each operand's operations. */
  private linkNodes(links: Link[], parents: Map<string, string | undefined>): void {
    const byId = new Map(this.nodes.map((node) => [node.id, node]));
    const lca = (ids: readonly string[]): string | undefined => {
      const chains = ids.map((id) => {
        const chain: string[] = [];
        for (let at = parents.get(id); at; at = parents.get(at)) chain.unshift(at);
        return chain;
      });
      let common: string | undefined;
      for (let i = 0; chains.every((chain) => i < chain.length && chain[i] === chains[0][i]); i++) common = chains[0][i];
      return common;
    };
    const ports = new Map<string, { node: NetNode; channel: NetChannel }>();
    links.forEach((link, index) => {
      const id = `c${index}:${link.channel.replace(/[^A-Za-z0-9_.]/g, '_')}`;
      const endpoint = (member: string, operations: NetOperation[], tags: string[]): NetEndpoint => ({ node: member, confidence: link.confidence, operations, tags });
      const channel: NetChannel = {
        id,
        kind: link.hub ? 'barrier' : 'channel',
        ref: { name: link.channel, kind: link.hub ? 'barrier' : 'channel', owner: [] },
        name: link.channel,
        type: '',
        shared: { read: false, write: false },
        ...(lca(link.members) ? { container: lca(link.members) } : {}),
        writers: [],
        readers: [],
        members: [],
        edges: [],
      };
      const tags = [...(link.hidden ? ['hidden'] : [])];
      for (const member of link.members) {
        const leaf = this.leaves.get(member);
        const node = byId.get(member);
        if (!leaf || !node) continue;
        const operations = leaf.uses.filter((use) => link.keys.some((key) => compatible(use, parseKey(key)))).map((use): NetOperation => ({
          kind: use.fields.some((field) => field.kind === '!') && !use.fields.some((field) => field.kind === '?') ? 'write' : use.fields.some((field) => field.kind === '?') && !use.fields.some((field) => field.kind === '!') ? 'read' : 'sync',
          channel: id,
          at: { uri: this.uri, span: use.at },
          confidence: use.conditional ? 'conditional' : 'exact',
        }));
        node.operations.push(...operations);
        if (link.hub) channel.members.push(endpoint(member, operations, ['sync', ...tags]));
        else if (member === link.from) channel.writers.push(endpoint(member, operations, tags));
        else if (member === link.to) channel.readers.push(endpoint(member, operations, tags));
        else channel.members.push(endpoint(member, operations, ['sync', ...tags]));
      }
      if (link.members.length === 1) {
        // The environment's side of a data channel: a port.
        const member = link.members[0];
        const direction = link.from === member ? 'out' : link.to === member ? 'in' : 'sync';
        const key = `${link.channel}|${direction}|${link.hidden}`;
        let port = ports.get(key);
        if (!port) {
          const node: NetNode = {
            id: `port:${index}:${link.channel.replace(/[^A-Za-z0-9_.]/g, '_')}`,
            kind: 'port',
            label: link.channel,
            name: `the environment on ${link.channel}`,
            ...(this.root.source ? { source: { uri: this.uri, span: this.globals.channels.get(link.keys[0].split('.')[0])?.span ?? this.root.source.span } } : {}),
            confidence: 'exact',
            port: { parameter: ports.size, name: link.channel, direction: direction === 'sync' ? 'sync' : direction, type: '' },
            channel: id,
            facts: ['the environment: no process of this network takes part in these events with it'],
            operations: [],
          };
          this.nodes.push(node);
          channel.port = node.id;
          port = { node, channel };
          ports.set(key, port);
          this.channels.push(channel);
        } else {
          // Another operand on the same environment channel: the same port.
          port.channel.writers.push(...channel.writers);
          port.channel.readers.push(...channel.readers);
          port.channel.members.push(...channel.members);
          for (const operation of byId.get(member)?.operations ?? []) if (operation.channel === id) operation.channel = port.channel.id;
        }
        const target = port.channel;
        const edgeId = `e${this.edges.length}:${target.id}`;
        const out = direction === 'out';
        // The port names the channel; its arrow needs no label of its own.
        this.edges.push({ id: edgeId, kind: 'channel', from: out ? member : port.node.id, to: out ? port.node.id : member, channel: target.id, confidence: link.confidence, role: 'direct', tags: [...tags, 'port', ...(direction === 'sync' ? ['undirected'] : [])] });
        target.edges.push(edgeId);
        return;
      }
      this.channels.push(channel);
      if (link.hub) {
        const hub: NetNode = {
          id: `h:${id}`,
          kind: 'barrier',
          ...(channel.container ? { parent: channel.container } : {}),
          label: truncateLabel(link.channel, 40),
          name: `the events ${link.channel}`,
          confidence: link.confidence,
          channel: id,
          facts: [`${link.members.length} processes take part in each of these events together`, ...(link.hidden ? ['hidden: internal to the network'] : [])],
          operations: [],
        };
        this.nodes.push(hub);
        channel.junction = hub.id;
        for (const member of link.members) {
          const edgeId = `e${this.edges.length}:${id}`;
          this.edges.push({ id: edgeId, kind: 'barrier', from: hub.id, to: member, channel: id, confidence: link.confidence, role: 'barrier', tags: ['sync', ...tags] });
          channel.edges.push(edgeId);
        }
        return;
      }
      const [first, second] = link.from ? [link.from, link.to!] : link.members;
      const edgeId = `e${this.edges.length}:${id}`;
      const plumbing = this.options.generated && link.keys.every((key) => key.startsWith('pj_'));
      this.edges.push({ id: edgeId, kind: 'channel', from: first, to: second, channel: id, ...(plumbing ? {} : { label: link.channel }), confidence: link.confidence, role: first === second ? 'self' : 'direct', tags: [...tags, ...(link.from ? [] : ['undirected'])] });
      channel.edges.push(edgeId);
    });
    // Events an operand performs alone that carry no data: listed on its box.
    for (const leaf of this.leaves.values()) {
      const node = byId.get(leaf.node);
      if (!node) continue;
      const alone = leaf.alone;
      // On a box of a network, what it does alone besides the arrows; a view of one process lists its events.
      const parts = [leaf.bindings, alone?.length ? `${leaf.path.length ? 'also' : 'events'} ${alone.slice(0, 4).join(', ')}${alone.length > 4 ? ', …' : ''}` : undefined].filter(Boolean);
      if (parts.length) node.detail = truncateLabel(parts.join(' · '), 44);
    }
  }
}

/** Whether a process term is a composition the view would unfold (through hiding, renaming and the like). */
function composes(e: Ex, depth = 0): boolean {
  if (depth > 16) return false;
  switch (e.k) {
    case 'par':
    case 'apar':
    case 'link':
      return true;
    case 'op':
      return e.op === '|||' || ((e.op === ';' || e.op === '[>' || e.op === '/\\') && composes(e.left, depth + 1));
    case 'repl':
      return e.op === '|||' || e.op === '[|' || e.op === '||';
    case 'hide':
    case 'rename':
      return composes(e.proc, depth + 1);
    case 'exception':
      return composes(e.left, depth + 1);
    case 'let':
      return composes(e.body, depth + 1);
    case 'if':
      return composes(e.then, depth + 1) || composes(e.else, depth + 1);
    default:
      return false;
  }
}

function bindUnknown(stmts: Extract<Ex, { k: 'repl' }>['stmts'], env: Env, globals: Globals): Env {
  const bound = new Map<string, Value>();
  for (const stmt of stmts) if (stmt.kind === 'gen') match(stmt.pattern, { t: 'unknown', why: 'a member of a replicated composition drawn once' }, globals, bound);
  return env.child(bound);
}

/** A renaming of whole channels: each channel to the channels it becomes (`[[ a <- b, a <- c ]]` makes a both b and c). */
export type RenameMap = Map<string, string[]>;

function renameMap(e: Extract<Ex, { k: 'rename' }>, env: Env, globals: Globals): { map?: RenameMap } {
  if (e.stmts) return {};
  const map: RenameMap = new Map();
  for (const [from, to] of e.pairs) {
    const a = evaluate(from, env);
    const b = evaluate(to, env);
    if (a.t !== 'dot' || b.t !== 'dot' || a.args.length || b.args.length || !globals.channels.has(a.head) || !globals.channels.has(b.head)) return {};
    const list = map.get(a.head) ?? [];
    if (!list.includes(b.head)) list.push(b.head);
    map.set(a.head, list);
  }
  return { map };
}

function renameText(map: RenameMap): string {
  return [...map].map(([a, list]) => list.map((b) => `${a}<-${b}`).join(',')).join(',');
}

function badgeOf(op: CompNode['op']): string {
  return op === '[|' ? '[| |]' : op === '||' ? '[ || ]' : op === '|||' ? '|||' : 'link';
}

function truncateLabel(text: string, limit: number): string {
  return text.length <= limit ? text : `${text.slice(0, limit - 1).trimEnd()}…`;
}

