type Events = Extract<Value, { t: 'events' }>;

export interface CspmNetworkOptions {
  uri: string;
  text: string;
  title?: string;
  /** Deepest chain of unfolded references (default 8). */
  maxDepth?: number;
  /** Operands per view before deeper compositions are drawn as one box (default 160). */
  maxLeaves?: number;
  /** Largest replicated composition drawn one box per member (default 16). */
  maxReplicated?: number;
  /**
   * The model was generated by Convert to CSP (its header says so): each box
   * shows the ProcessJ line its definition's comment names, and the
   * translator's own events (`pj_fork_…`, `pj_join_…`, `pj_end`) are drawn
   * without labels.
   */
  generated?: boolean;
}

/** A process a view can start from. */
export interface CspmRoot {
  id: string;
  /** What checks name as their target (the process as written, on one line). */
  name: string;
  label: string;
  expr: Ex;
  source: SourceRef;
  /** `asserted`: an assertion is about it; `definition`: a process defined without parameters. */
  section: 'asserted' | 'definition';
  /** The definition this root is, when it is one. */
  definition?: string;
}

/** One field of an event an operand performs. */
export interface UseField {
  value?: Value;
  kind: '.' | '?' | '!';
}

/** An event an operand performs: `pickup.0.1`, `left?x`, `right!x`. */
export interface Use {
  channel: string;
  fields: UseField[];
  /** Where it is written: the event of the prefix. */
  at: Span;
  /** Under a choice, a guard, a condition the walk could not decide. */
  conditional: boolean;
  /** CHAOS(A)/RUN(A): one of the events of a set. */
  fromSet?: boolean;
  /** Inside a renaming that is not followed (its text): the event may be another one. */
  renamed?: string;
}

export type Wrapper =
  | { kind: 'call'; name: string; label: string; site: Span; definition?: Definition }
  | { kind: 'hide'; set?: Events; text: string }
  | { kind: 'rename'; text: string; map?: RenameMap }
  | { kind: 'after'; text: string }
  | { kind: 'function'; name: string };

export interface LeafNode {
  kind: 'leaf';
  node: string;
  path: ProcessPath;
  label: string;
  expr: Ex;
  env: Env;
  wrappers: Wrapper[];
  uses: Use[];
  /** The definition the operand runs, when it is a reference. */
  definition?: string;
  /** The walk of its events stopped short (budget, an opaque term, a value it could not compute). */
  partial: string[];
  /** Events hidden inside the operand itself. */
  hidden: Use[];
  replicated?: { count?: number; text: string };
  /** The values an inline operand of a replicated composition is drawn for (`i = 0`). */
  bindings?: string;
  /** Events it performs with nobody else of the network, that carry no data (listed on its box). */
  alone?: string[];
  /** A composition drawn as one box: why it was not unfolded. */
  cut?: string;
}

export interface CompNode {
  kind: 'comp';
  node: string;
  path: ProcessPath;
  /** `[|`, `||` (alphabetized), `|||`, `link`. */
  op: '[|' | '||' | '|||' | 'link';
  label: string;
  /** Operator text: `[| {| pickup, putdown |} |]`, `||| i : PHILS`. */
  operator: string;
  children: Array<LeafNode | CompNode>;
  sync?: Events;
  /** Alphabet of each child, for `||`. */
  alphabets?: Array<Events | undefined>;
  wrappers: Wrapper[];
  span: Span;
  replicated?: { count?: number; text: string };
  /** Whether the synchronisation set or an alphabet could not be computed. */
  unknownSync?: string;
  /**
   * How the operands were written, when a chain of one operator was drawn as
   * one composition (`A ||| (B ||| C)` is [0, [1, 2]]): FDR keeps the binary
   * tree, and its nodes are matched to the operands by this shape.
   */
  shape?: Shape;
}

/** An operand's index, or a binary node of the operator as written. */
export type Shape = number | [Shape, Shape];

export type TreeNode = LeafNode | CompNode;

/** A drawn link: the operands that take part together in some events. */
export interface Link {
  channel: string;
  /** The events, as keys (`pickup.0.1`, `mid`). */
  keys: string[];
  members: string[];
  hub: boolean;
  hidden: boolean;
  from?: string;
  to?: string;
  confidence: Confidence;
}

/** Events an operand performs that a composition synchronises on but the other side never does: they can never happen. */
export interface Blocked {
  key: string;
  /** The operands that would perform them. */
  users: string[];
  /** The operands of the side that never does (leaf ids). */
  missing: string[];
  /** The composition, as written. */
  operator: string;
  /** Whether every operand involved was walked completely. */
  proven: boolean;
}

export interface CspmView {
  root: CspmRoot;
  view: NetworkView;
  tree: TreeNode;
  links: Link[];
  blocked: Blocked[];
  /** Leaf node id -> leaf. */
  leaves: Map<string, LeafNode>;
}

/** The roots of a file: asserted processes, then MAIN/SYSTEM/main, then every process defined without parameters. */
export function cspmRoots(file: CspmFile, globals: Globals, uri: string, text: string): CspmRoot[] {
  const out: CspmRoot[] = [];
  const seen = new Set<string>();
  const ids = new Set<string>();
  const add = (expr: Ex, section: CspmRoot['section'], source: Span, definition?: string): void => {
    const name = definition ?? spanText(text, expr.span);
    if (!name || seen.has(name)) return;
    seen.add(name);
    let id = `view:${name.replace(/[^A-Za-z0-9_'.]+/g, '_').slice(0, 60)}`;
    for (let n = 2; ids.has(id); n++) id = `${id.replace(/~\d+$/, '')}~${n}`;
    ids.add(id);
    out.push({ id, name, label: name, expr, source: { uri, span: source }, section, ...(definition ? { definition } : {}) });
  };
  const nameExpr = (definition: Definition): Ex => ({ k: 'name', name: definition.name.name, span: definition.name.span });
  for (const decl of file.decls) {
    if (decl.kind !== 'assert') continue;
    const impl = decl.impl;
    if (impl.k === 'name') {
      const definition = globals.definitions.get(impl.name)?.[0];
      if (definition && definition.params.length === 0) {
        add(nameExpr(definition), 'asserted', definition.name.span, impl.name);
        continue;
      }
    }
    add(impl, 'asserted', impl.span);
  }
  const definitions = file.decls.filter((decl): decl is Definition => decl.kind === 'def' && decl.params.length === 0 && isProcessExpr(decl.body, globals));
  for (const main of ['MAIN', 'SYSTEM', 'main', 'System']) {
    const definition = definitions.find((decl) => decl.name.name === main);
    if (definition) add(nameExpr(definition), 'definition', definition.name.span, main);
  }
  for (const definition of definitions) add(nameExpr(definition), 'definition', definition.name.span, definition.name.name);
  return out;
}

/** The root a view opens on: MAIN, SYSTEM or main; else the first asserted root that is a network; else the first network. */
export function defaultRoot(views: readonly CspmView[]): CspmView | undefined {
  const named = views.find((entry) => entry.root.definition && ['MAIN', 'SYSTEM', 'main', 'System'].includes(entry.root.definition) && entry.tree.kind === 'comp');
  return named ?? views.find((entry) => entry.root.section === 'asserted' && entry.tree.kind === 'comp') ?? views.find((entry) => entry.tree.kind === 'comp') ?? views[0];
}

/** Build the view of one root. */
export function buildCspmView(root: CspmRoot, globals: Globals, options: CspmNetworkOptions): CspmView {
  return new ViewBuilder(root, globals, options).build();
}

/** The whole model: every root's view, built now. */
export function buildCspmNetwork(file: CspmFile, options: CspmNetworkOptions): { model: NetworkModel; views: CspmView[]; globals: Globals } {
  const globals = new Globals(file.decls, options.text);
  const views = cspmRoots(file, globals, options.uri, options.text).map((root) => buildCspmView(root, globals, options));
  return { model: cspmModel(views, options), views, globals };
}

export function cspmModel(views: readonly CspmView[], options: Pick<CspmNetworkOptions, 'uri' | 'title'>): NetworkModel {
  return {
    version: 1,
    generator: 'processj-lsp',
    uri: options.uri,
    title: options.title ?? decodeURIComponent(options.uri.split('/').pop() ?? 'model.csp'),
    views: views.map((entry) => entry.view),
    defaultView: defaultRoot(views)?.view.id ?? '',
    language: 'cspm',
  };
}

