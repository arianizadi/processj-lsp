/**
 * The process network of a CSPm file, in the model the graph renderers and
 * the viewer already draw for ProcessJ (src/graph/network.ts): the operands
 * of a parallel composition are boxes, and the events they synchronise on
 * are the arrows between them.
 *
 * A view starts at a root process: one an assertion is about, MAIN, SYSTEM
 * or main, or any process defined without parameters. A reference whose
 * definition is itself a composition (`SYSTEM = PHILS [| X |] FORKS`, then
 * `PHILS = ||| i : S @ PHIL(i)`) is unfolded in place, through hiding,
 * renaming, `[| A |>`, `;` and FDR's compression functions, to a bounded
 * depth and never into itself. Replicated compositions over a set the
 * evaluator can enumerate (src/cspm/eval.ts) get one box per member; a
 * larger or unknown set is one box drawn x N.
 *
 * What each operand does comes from walking its definition, following the
 * references it makes (with their arguments) up to a budget: every prefix is
 * an event on a channel with some fields known. Which events two operands
 * share follows CSP's semantics exactly: an event synchronises at a
 * generalized parallel whose set holds it, at an alphabetized parallel whose
 * two alphabets hold it, never at an interleaving; hiding makes it internal
 * from there up. So an arrow joins the operands that must take part in the
 * same events together: from the one that only outputs (`!`) to the one that
 * only inputs (`?`), an undirected link otherwise, and a hub when three or
 * more take part in each such event (a barrier). An event an operand
 * performs on its own is the environment's: a data channel becomes a port,
 * any other event is listed on the box.
 *
 * Identity follows src/verification.ts with spans in the .csp file: an
 * operand's path adds { kind: 'branch', site: the composition, index } per
 * binary or flattened composition, { kind: 'par-for', site, index } per
 * replicated one (no index when it is drawn once), and { kind: 'call', site:
 * the reference } for every reference unfolded on the way to a nested
 * composition. Nothing here claims more than the text establishes: what the
 * walk could not work out is said in the notes and facts of the view.
 */
import type { Span } from '../parser/ast';
import { pathKey, type Confidence, type NetChannel, type NetEdge, type NetEndpoint, type NetNode, type NetOperation, type NetworkModel, type NetworkView } from '../graph/network';
import type { ProcessPath, SourceRef, SpawnSite } from '../verification';
import type { CspmFile, Decl, Definition, Ex } from './ast';
import { BUILTIN_PROCESSES, comprehend, covers, Env, evaluate, flatten, Globals, isProcessExpr, letEnv, match, show, showPat, toEvents, TRANSPARENT_FUNCTIONS, type EventPat, type Value } from './eval';
