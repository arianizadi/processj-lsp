/**
 * A tolerant parser for the CSPm people write for FDR: channel, datatype,
 * subtype and nametype declarations, definitions with (pattern) parameters,
 * every process operator of FDR's manual with its precedence, replicated
 * operators, sets, sequences and comprehensions, let/within, lambdas,
 * include, external/transparent and assert lines.
 *
 * A file is first split into declarations at line starts (a line whose first
 * token begins a definition `name(...) =` or a keyword declaration, outside
 * brackets and let blocks), then each declaration is parsed on its own: an
 * error costs that declaration only (it becomes `opaque`, with a diagnostic),
 * and within an expression unknown syntax becomes an opaque node with its
 * span. Timed sections and modules are read past with a note. The parser
 * never throws.
 *
 * Precedence follows FDR's manual, from tightest: application and renaming;
 * unary minus, `#`, `^`; `* / %`; `+ -`; comparisons; `not`, `and`, `or`;
 * `.`; guard `&` and prefix `->`; `;`; `[>`; `/\`; `[| A |>`; `[]`; `|~|`;
 * the parallels `[| A |]`, `[A || B]`, `[a <-> b]`; `|||`; and hiding `\`
 * last. `if`, `let` and the replicated operators extend as far as possible.
 */
import type { AssertProperty, BinOp, Constructor, CspmDiagnostic, CspmFile, Decl, Definition, Ex, Field, Ident, ProcOp, ReplOp, Span, Stmt } from './ast';
import { lex, type Comment, type Token } from './lexer';

const DECL_KEYWORDS = new Set(['channel', 'datatype', 'subtype', 'nametype', 'assert', 'include', 'external', 'transparent', 'print', 'Timed', 'module', 'instance']);
const RESERVED = new Set(['if', 'then', 'else', 'let', 'within', 'not', 'and', 'or', 'true', 'false', ...DECL_KEYWORDS, 'exports', 'endmodule']);
const OPENERS: Record<string, string> = { '(': ')', '[': ']', '{': '}', '[|': '|]', '{|': '|}', '[[': ']]' };
const CLOSERS = new Set([')', ']', '}', '|]', '|}', ']]', '|>']);
const REFINES = new Set(['[T=', '[F=', '[FD=', '[R=', '[RD=', '[V=']);

class ParseError extends Error {
  constructor(message: string, readonly span: Span) {
    super(message);
  }
}

/** Parse a CSPm file. Never throws: what it cannot read is reported and kept as opaque. */
export function parseCspm(text: string): CspmFile {
  const { tokens, comments, problems } = lex(text);
  const diagnostics: CspmDiagnostic[] = problems.map((problem) => ({ ...problem, severity: 'error' }));
  for (const token of tokens) if (token.kind === 'error') diagnostics.push({ message: `unexpected character '${token.text}'`, span: token.span, severity: 'error' });
  const decls: Decl[] = [];
  const ranges = splitDeclarations(tokens.filter((token) => token.kind !== 'error'));
  for (const range of ranges) {
    const decl = parseDeclaration(range, text, diagnostics);
    if (decl) decls.push(decl);
  }
  attachComments(decls, comments);
  const header = /^\s*-- Generated by processj-lsp from (.+?)\. /.exec(text);
  return { decls, diagnostics, ...(header ? { generatedFrom: header[1] } : {}) };
}

/** The tokens of each declaration, each ending with an eof sentinel. */
function splitDeclarations(tokens: Token[]): Token[][] {
  const out: Token[][] = [];
  let current: Token[] = [];
  const stack: string[] = [];
  let lets = 0;
  const flush = (end: Token): void => {
    // The sentinel sits where the declaration ends, so `this declaration ends too early` points at it.
    const last = current[current.length - 1];
    if (current.length) out.push([...current, { ...end, kind: 'eof', text: '', span: { start: last.span.end, end: last.span.end }, first: false }]);
    current = [];
  };
  for (let i = 0; i < tokens.length; i++) {
    const token = tokens[i];
    if (token.kind === 'eof') break;
    // A Timed section or a module: everything up to its closing brace or endmodule is one declaration.
    if (token.first && !stack.length && !lets && token.kind === 'ident' && (token.text === 'Timed' || token.text === 'module' || token.text === 'instance')) {
      flush(token);
      let j = i;
      if (token.text === 'module') {
        while (j < tokens.length - 1 && tokens[j].text !== 'endmodule') j++;
      } else if (token.text === 'Timed') {
        while (j < tokens.length - 1 && tokens[j].text !== '{') j++;
        let depth = 0;
        for (; j < tokens.length - 1; j++) {
          if (tokens[j].text === '{' || tokens[j].text === '{|') depth++;
          else if (tokens[j].text === '}' || tokens[j].text === '|}') {
            depth--;
            if (depth === 0) break;
          }
        }
      } else {
        // `instance M = N(args)`: one line.
        while (j + 1 < tokens.length - 1 && !tokens[j + 1].first) j++;
      }
      current = tokens.slice(i, Math.min(j + 1, tokens.length - 1));
      flush(tokens[Math.min(j + 1, tokens.length - 1)]);
      i = j;
      continue;
    }
    if (token.first && !stack.length && !lets && current.length && startsDeclaration(tokens, i)) flush(token);
    current.push(token);
    if (token.kind === 'op' && OPENERS[token.text]) stack.push(OPENERS[token.text]);
    else if (token.kind === 'op' && CLOSERS.has(token.text)) {
      // `[| A |>` closes with `|>`; a stray closer is the parser's to report.
      const expected = token.text === '|>' ? '|]' : token.text;
      const at = stack.lastIndexOf(expected);
      if (at >= 0) stack.length = at;
      // `]]` also closes two `[` (`:[deadlock free [F]]`).
      else if (token.text === ']]' && stack[stack.length - 1] === ']' && stack[stack.length - 2] === ']') stack.length -= 2;
    } else if (token.kind === 'ident' && token.text === 'let') lets++;
    else if (token.kind === 'ident' && token.text === 'within' && lets > 0) lets--;
  }
  flush(tokens[tokens.length - 1]);
  return out;
}

/** A keyword declaration, or a definition head `name(...)(...) =`. */
function startsDeclaration(tokens: Token[], i: number): boolean {
  const token = tokens[i];
  if (token.kind !== 'ident') return false;
  if (DECL_KEYWORDS.has(token.text)) return true;
  if (RESERVED.has(token.text)) return false;
  return definitionHeadEnd(tokens, i) !== undefined;
}

/** Index of the `=` of a definition head starting at i, or `::` of a signature. */
function definitionHeadEnd(tokens: Token[], i: number): number | undefined {
  let j = i + 1;
  // `f, g :: T`
  while (tokens[j]?.text === ',' && tokens[j + 1]?.kind === 'ident') j += 2;
  if (tokens[j]?.text === '::') return j;
  j = i + 1;
  while (tokens[j]?.text === '(') {
    let depth = 0;
    for (; j < tokens.length; j++) {
      const text = tokens[j].kind === 'op' ? tokens[j].text : '';
      if (OPENERS[text]) depth++;
      else if (CLOSERS.has(text)) depth--;
      if (depth === 0) break;
      if (tokens[j].kind === 'eof') return undefined;
    }
    j++;
  }
  return tokens[j]?.kind === 'op' && tokens[j].text === '=' ? j : undefined;
}

function parseDeclaration(tokens: Token[], text: string, diagnostics: CspmDiagnostic[]): Decl | undefined {
  const span = { start: tokens[0].span.start, end: tokens[tokens.length - 2]?.span.end ?? tokens[0].span.end };
  const head = tokens[0];
  if (head.text === 'Timed' || head.text === 'module' || head.text === 'instance') {
    const what = head.text === 'Timed' ? 'a Timed section' : head.text === 'module' ? 'a module' : 'a module instance';
    diagnostics.push({ message: `${what} is not read by the graph (FDR still checks it)`, span: head.span, severity: 'info' });
    return { kind: 'skipped', what, span };
  }
  const parser = new Parser(tokens, text);
  try {
    const decl = parser.declaration();
    if (!parser.atEnd()) {
      const extra = parser.peek();
      throw new ParseError(`unexpected '${extra.text}'`, extra.span);
    }
    return decl;
  } catch (error) {
    // Out of stack on some nesting the depth limit does not count: the declaration is opaque, as any it cannot read.
    if (error instanceof RangeError) {
      const reason = 'this declaration is nested too deeply for the graph to read (FDR still checks it)';
      diagnostics.push({ message: reason, span: head.span, severity: 'warning' });
      return { kind: 'opaque', text: sourceText(text, span), reason, span };
    }
    if (!(error instanceof ParseError)) throw error;
    // Too deep to read is not a syntax error: FDR may well accept it.
    diagnostics.push({ message: error.message, span: error.span, severity: /nested more than/.test(error.message) ? 'warning' : 'error' });
    return { kind: 'opaque', text: sourceText(text, span), reason: error.message, span };
  }
}

function sourceText(text: string, span: Span): string {
  const lines = text.split('\n');
  if (span.start.line === span.end.line) return (lines[span.start.line] ?? '').slice(span.start.col, span.end.col);
  return [
    (lines[span.start.line] ?? '').slice(span.start.col),
    ...lines.slice(span.start.line + 1, span.end.line),
    (lines[span.end.line] ?? '').slice(0, span.end.col),
  ].join('\n');
}

/** The comment lines directly above a definition (own lines, nothing between). */
function attachComments(decls: Decl[], comments: Comment[]): void {
  const byEnd = new Map<number, Comment>();
  for (const comment of comments) if (comment.own) byEnd.set(comment.endLine, comment);
  for (const decl of decls) {
    if (decl.kind !== 'def') continue;
    const lines: string[] = [];
    for (let line = decl.span.start.line - 1; byEnd.has(line); line = byEnd.get(line)!.line - 1) lines.unshift(byEnd.get(line)!.text);
    const text = lines.join(' ').trim();
    if (text) decl.comment = text;
  }
}

/** Deepest nesting of expressions read (parentheses, sets, arguments); deeper is an opaque declaration. */
const MAX_NESTING = 100;

class Parser {
  private i = 0;

  constructor(private readonly tokens: Token[], private readonly text: string) {}

  peek(offset = 0): Token {
    return this.tokens[Math.min(this.i + offset, this.tokens.length - 1)];
  }

  atEnd(): boolean {
    return this.peek().kind === 'eof';
  }

  private next(): Token {
    const token = this.peek();
    if (token.kind !== 'eof') this.i++;
    return token;
  }

  private is(text: string, offset = 0): boolean {
    const token = this.peek(offset);
    return (token.kind === 'op' || token.kind === 'ident') && token.text === text;
  }

  private accept(text: string): Token | undefined {
    return this.is(text) ? this.next() : undefined;
  }

  private expect(text: string, what?: string): Token {
    const token = this.peek();
    if (this.is(text)) return this.next();
    throw new ParseError(`expected '${text}'${what ? ` ${what}` : ''}${token.kind === 'eof' ? ' before the end of the declaration' : `, found '${token.text}'`}`, token.span);
  }

  private last(): Token {
    return this.tokens[Math.max(0, this.i - 1)];
  }

  private span(start: Token | Span): Span {
    const from = 'span' in start ? start.span.start : start.start;
    return { start: from, end: this.last().span.end };
  }

  private ident(what: string): Ident {
    const token = this.peek();
    if (token.kind !== 'ident' || RESERVED.has(token.text)) throw new ParseError(`expected ${what}${token.kind === 'eof' ? '' : `, found '${token.text}'`}`, token.span);
    this.next();
    return { name: token.text, span: token.span };
  }

  // -------------------------------------------------------------------------
  // Declarations
  // -------------------------------------------------------------------------

  declaration(): Decl {
    const start = this.peek();
    switch (start.kind === 'ident' ? start.text : '') {
      case 'channel': {
        this.next();
        const names = [this.ident('a channel name')];
        while (this.accept(',')) names.push(this.ident('a channel name'));
        const type = this.accept(':') ? this.dotted() : undefined;
        return { kind: 'channel', names, ...(type ? { type } : {}), span: this.span(start) };
      }
      case 'datatype':
      case 'subtype': {
        this.next();
        const name = this.ident('a type name');
        this.expect('=');
        const constructors: Constructor[] = [];
        do {
          const ctor = this.ident('a constructor');
          const fields: Ex[] = [];
          while (this.accept('.')) fields.push(this.orExpr());
          constructors.push({ name: ctor, fields });
        } while (this.accept('|'));
        return { kind: 'datatype', subtype: start.text === 'subtype', name, constructors, span: this.span(start) };
      }
      case 'nametype': {
        this.next();
        const name = this.ident('a type name');
        this.expect('=');
        return { kind: 'nametype', name, value: this.dotted(), span: this.span(start) };
      }
      case 'include': {
        this.next();
        const file = this.next();
        if (file.kind !== 'str') throw new ParseError('expected a file name in quotes after include', file.span);
        return { kind: 'include', file: unquote(file.text), span: this.span(start) };
      }
      case 'external':
      case 'transparent': {
        this.next();
        const names = [this.ident('a name')];
        while (this.accept(',')) names.push(this.ident('a name'));
        return { kind: start.text as 'external' | 'transparent', names, span: this.span(start) };
      }
      case 'print': {
        this.next();
        return { kind: 'print', expr: this.expr(), span: this.span(start) };
      }
      case 'assert':
        return this.assertion();
      default:
        return this.definition();
    }
  }

  private definition(): Definition | Decl {
    const start = this.peek();
    const name = this.ident('a definition');
    if (this.is(',') || this.is('::')) {
      // A type signature: `f, g :: (Int) -> Int`. Read past it.
      const names = [name];
      while (this.accept(',')) names.push(this.ident('a name'));
      this.expect('::');
      while (!this.atEnd()) this.next();
      return { kind: 'signature', names, span: this.span(start) };
    }
    const params: Ex[][] = [];
    while (this.is('(')) {
      this.next();
      const group: Ex[] = [];
      if (!this.is(')')) {
        do group.push(this.expr()); while (this.accept(','));
      }
      this.expect(')', 'after the parameters');
      params.push(group);
    }
    this.expect('=', `after ${name.name}`);
    const body = this.expr();
    return { kind: 'def', name, params, body, span: this.span(start) };
  }

  private assertion(): Decl {
    const start = this.next();
    const negated = !!this.accept('not');
    const first = this.expr();
    const token = this.peek();
    if (token.kind === 'op' && REFINES.has(token.text)) {
      this.next();
      const impl = this.expr();
      const options = this.options();
      return { kind: 'assert', negated, refinement: { model: token.text.slice(1, -1), spec: first }, impl, ...(options ? { options } : {}), text: this.textOf(start), span: this.span(start) };
    }
    if (this.is(':') && this.is('[', 1)) {
      this.next();
      const open = this.next();
      // `:[deadlock free [F]]`, `:[has trace [T]]: <a, b>`: the words, then an optional model in brackets.
      const words: string[] = [];
      let model: string | undefined;
      let depth = 1;
      while (!this.atEnd() && depth > 0) {
        const t = this.next();
        if (t.text === '[') {
          depth++;
          const m = this.next();
          model = m.text;
          continue;
        }
        if (t.text === ']') depth--;
        else if (t.text === ']]') depth -= 2;
        else if (depth === 1) words.push(t.text);
      }
      if (depth > 0) throw new ParseError("this assertion's property is never closed with ']'", open.span);
      const name = words.join(' ');
      let trace: Ex | undefined;
      if (name === 'has trace' || name.startsWith('has trace')) {
        this.expect(':', 'before the trace');
        trace = this.orExpr();
      }
      const options = this.options();
      return { kind: 'assert', negated, property: { name: name as AssertProperty, ...(model ? { model } : {}), ...(trace ? { trace } : {}) }, impl: first, ...(options ? { options } : {}), text: this.textOf(start), span: this.span(start) };
    }
    throw new ParseError(`expected a refinement ([T=, [F=, [FD=) or a property (:[deadlock free]) in this assertion${token.kind === 'eof' ? '' : `, found '${token.text}'`}`, token.span);
  }

  /** `:[tau priority]: {...}` and the like, kept as text. */
  private options(): string | undefined {
    if (!this.is(':')) return undefined;
    const from = this.peek();
    while (!this.atEnd()) this.next();
    return this.textOf(from);
  }

  private textOf(start: Token): string {
    const end = this.last();
    return this.text.slice(start.offset + (start.text === 'assert' ? 6 : 0), end.offset + end.text.length).replace(/\s+/g, ' ').trim();
  }

  // -------------------------------------------------------------------------
  // Expressions: processes, lowest precedence first
  // -------------------------------------------------------------------------

  /** Nested expressions being read: each costs many stack frames through the precedence levels. */
  private depth = 0;

  expr(): Ex {
    if (this.depth >= MAX_NESTING) throw new ParseError(`this is nested more than ${MAX_NESTING} levels deep, deeper than the graph reads (FDR still checks it)`, this.peek().span);
    this.depth++;
    try {
      return this.hide();
    } finally {
      this.depth--;
    }
  }

  private hide(): Ex {
    let left = this.interleave();
    while (this.is('\\')) {
      this.next();
      const set = this.interleave();
      left = { k: 'hide', proc: left, set, span: join(left.span, set.span) };
    }
    return left;
  }

  private interleave(): Ex {
    let left = this.parallel();
    while (this.is('|||')) {
      this.next();
      const right = this.parallel();
      left = { k: 'op', op: '|||', left, right, span: join(left.span, right.span) };
    }
    return left;
  }

  private parallel(): Ex {
    let left = this.internal();
    for (;;) {
      if (this.is('[|') && this.syncCloser() === '|]') {
        this.next();
        const sync = this.expr();
        this.expect('|]', 'to close the synchronisation set');
        const right = this.internal();
        left = { k: 'par', left, right, sync, span: join(left.span, right.span) };
      } else if (this.is('[') && !this.is('[[')) {
        this.next();
        const a = this.expr();
        if (this.accept('||')) {
          const b = this.expr();
          this.expect(']', 'to close the alphabets');
          const right = this.internal();
          left = { k: 'apar', left, right, alphaLeft: a, alphaRight: b, span: join(left.span, right.span) };
        } else if (this.accept('<->')) {
          const pairs: Array<[Ex, Ex]> = [[a, this.expr()]];
          while (this.accept(',')) {
            const from = this.expr();
            this.expect('<->');
            pairs.push([from, this.expr()]);
          }
          this.expect(']', 'to close the link');
          const right = this.internal();
          left = { k: 'link', left, right, pairs, span: join(left.span, right.span) };
        } else throw new ParseError(`expected '||' or '<->' in a parallel, found '${this.peek().text}'`, this.peek().span);
      } else return left;
    }
  }

  /** Whether the `[|` here closes with `|]` (a parallel) or `|>` (an exception). */
  private syncCloser(): string | undefined {
    let depth = 0;
    for (let j = this.i; j < this.tokens.length; j++) {
      const t = this.tokens[j];
      if (t.kind === 'eof') return undefined;
      if (t.kind !== 'op') continue;
      if (OPENERS[t.text]) depth++;
      else if (CLOSERS.has(t.text)) {
        depth--;
        if (depth === 0) return t.text;
      }
    }
    return undefined;
  }

  private internal(): Ex {
    return this.binaryProc(['|~|'], () => this.external());
  }

  private external(): Ex {
    return this.binaryProc(['[]'], () => this.exception());
  }

  private exception(): Ex {
    let left = this.interrupt();
    while (this.is('[|') && this.syncCloser() === '|>') {
      this.next();
      const set = this.expr();
      this.expect('|>');
      const right = this.interrupt();
      left = { k: 'exception', left, right, set, span: join(left.span, right.span) };
    }
    return left;
  }

  private interrupt(): Ex {
    return this.binaryProc(['/\\'], () => this.slide());
  }

  private slide(): Ex {
    return this.binaryProc(['[>'], () => this.sequential());
  }

  private sequential(): Ex {
    return this.binaryProc([';'], () => this.prefix());
  }

  private binaryProc(ops: ProcOp[], operand: () => Ex): Ex {
    let left = operand();
    for (;;) {
      const op = ops.find((candidate) => this.is(candidate));
      if (!op) return left;
      this.next();
      const right = operand();
      left = { k: 'op', op, left, right, span: join(left.span, right.span) };
    }
  }

  /** Prefix `e -> P`, input and output fields, guards `b & P`, or a plain term. */
  private prefix(): Ex {
    const start = this.peek();
    if (this.startsLowForm()) return this.lowForm();
    const head = this.dotted();
    const fields: Field[] = [];
    if (head.k === 'dot') {
      for (const part of head.parts.slice(1)) fields.push({ kind: '.', expr: part, span: part.span });
    }
    while (this.is('?') || this.is('!') || this.is('$')) {
      const mark = this.next();
      if (mark.text === '!') {
        const value = this.orExpr();
        fields.push({ kind: '!', expr: value, span: join(mark.span, value.span) });
      } else {
        const pattern = this.orExpr();
        const restrict = this.accept(':') ? this.orExpr() : undefined;
        fields.push({ kind: mark.text as '?' | '$', expr: pattern, ...(restrict ? { restrict } : {}), span: join(mark.span, (restrict ?? pattern).span) });
      }
      // `c?x.y` and `c!x.y`: dots after a field are fields of their own.
      while (this.is('.')) {
        this.next();
        const value = this.orExpr();
        fields.push({ kind: '.', expr: value, span: value.span });
      }
    }
    if (this.is('->')) {
      const eventSpan = this.span(start);
      this.next();
      const body = this.prefix();
      const channel = head.k === 'dot' ? head.parts[0] : head;
      return { k: 'prefix', head: channel, fields, body, eventSpan, span: join(start.span, body.span) };
    }
    if (fields.some((field) => field.kind !== '.')) throw new ParseError(`expected '->' after the event, found '${this.peek().text}'`, this.peek().span);
    if (this.is('&')) {
      this.next();
      const body = this.prefix();
      return { k: 'guard', cond: head, body, span: join(head.span, body.span) };
    }
    return head;
  }

  /** `if`, `let`, a lambda or a replicated operator: they extend as far as possible. */
  private startsLowForm(): boolean {
    const t = this.peek();
    if (t.kind === 'ident') return t.text === 'if' || t.text === 'let';
    if (t.kind !== 'op') return false;
    if (t.text === '\\') return true;
    if (t.text === '[]' || t.text === '|~|' || t.text === '|||' || t.text === ';' || t.text === '||' || t.text === '/\\') return true;
    return t.text === '[|';
  }

  private lowForm(): Ex {
    const start = this.next();
    if (start.text === 'if') {
      const cond = this.expr();
      this.expect('then');
      const then = this.expr();
      this.expect('else');
      const otherwise = this.expr();
      return { k: 'if', cond, then, else: otherwise, span: this.span(start) };
    }
    if (start.text === 'let') {
      const decls: Decl[] = [];
      while (!this.is('within')) {
        if (this.atEnd()) throw new ParseError("this let has no 'within'", start.span);
        const at = this.peek();
        const before = this.i;
        if (at.kind === 'ident' && (at.text === 'channel' || at.text === 'datatype' || at.text === 'nametype' || at.text === 'external' || at.text === 'transparent')) decls.push(this.declaration());
        else decls.push(this.definition());
        if (this.i === before) throw new ParseError('expected a definition in this let', at.span);
      }
      this.next();
      const body = this.expr();
      return { k: 'let', decls, body, span: this.span(start) };
    }
    if (start.text === '\\') {
      const params = [this.orExpr()];
      while (this.accept(',')) params.push(this.orExpr());
      this.expect('@', 'after the parameters of this lambda');
      const body = this.expr();
      return { k: 'lambda', params, body, span: this.span(start) };
    }
    // A replicated operator.
    let sync: Ex | undefined;
    let op = start.text as ReplOp;
    if (start.text === '[|') {
      sync = this.expr();
      this.expect('|]', 'to close the synchronisation set');
      op = '[|';
    }
    const stmts = this.stmts('@');
    this.expect('@', 'after the replicated statements');
    let alpha: Ex | undefined;
    if (op === '||') {
      this.expect('[', "before the alphabet of a replicated '||'");
      alpha = this.expr();
      this.expect(']', 'to close the alphabet');
    }
    const body = this.expr();
    return { k: 'repl', op, stmts, body, ...(sync ? { sync } : {}), ...(alpha ? { alpha } : {}), span: this.span(start) };
  }

  /** Comprehension or replicated statements up to `end` (not consumed). */
  private stmts(end: string, alsoEnd?: string): Stmt[] {
    const out: Stmt[] = [];
    if (this.is(end) || (alsoEnd && this.is(alsoEnd))) return out;
    do {
      // `x <- S` and `x : S` bind; anything else is a condition.
      const first = this.dottedNoCompare();
      if (this.is('<-') || this.is(':')) {
        this.next();
        const source = this.dottedNoCompare();
        out.push({ kind: 'gen', pattern: first, source, span: join(first.span, source.span) });
      } else {
        const expr = this.continueCondition(first);
        out.push({ kind: 'cond', expr, span: expr.span });
      }
    } while (this.accept(','));
    return out;
  }

  /** A condition statement that started like a pattern: finish it as a boolean expression. */
  private continueCondition(first: Ex): Ex {
    let left = first;
    const cmp = ['==', '!=', '<=', '>=', '<', '>'] as const;
    const op = cmp.find((candidate) => this.is(candidate));
    // Inside a sequence comprehension the closing `>` is not a comparison.
    if (op && !(op === '>' && this.closesSequence())) {
      this.next();
      const right = this.addExpr();
      left = { k: 'bin', op, left, right, span: join(left.span, right.span) };
    }
    for (;;) {
      if (this.is('and') || this.is('or')) {
        const word = this.next().text as 'and' | 'or';
        const right = this.notExpr();
        left = { k: 'bin', op: word, left, right, span: join(left.span, right.span) };
      } else return left;
    }
  }

  private seqDepth = 0;

  private closesSequence(): boolean {
    return this.seqDepth > 0 && this.is('>') && (this.peek(1).kind === 'eof' || [',', ')', '}', ']', '|}', '|]', '->', '^', ';', '@', '&', '[]', '|~|', '|||', '\\', '=', '.'].includes(this.peek(1).text) || this.peek(1).first);
  }

  // -------------------------------------------------------------------------
  // Values
  // -------------------------------------------------------------------------

  /** `a.b.c`, each part an `or` expression. */
  private dotted(): Ex {
    const first = this.orExpr();
    if (!this.is('.')) return first;
    const parts = [first];
    while (this.accept('.')) parts.push(this.orExpr());
    return { k: 'dot', parts, span: join(first.span, parts[parts.length - 1].span) };
  }

  /** Dotted, without comparisons (a generator's pattern and source). */
  private dottedNoCompare(): Ex {
    const first = this.addExpr();
    if (!this.is('.')) return first;
    const parts = [first];
    while (this.accept('.')) parts.push(this.addExpr());
    return { k: 'dot', parts, span: join(first.span, parts[parts.length - 1].span) };
  }

  orExpr(): Ex {
    let left = this.andExpr();
    while (this.is('or')) {
      this.next();
      const right = this.andExpr();
      left = { k: 'bin', op: 'or', left, right, span: join(left.span, right.span) };
    }
    return left;
  }

  private andExpr(): Ex {
    let left = this.notExpr();
    while (this.is('and')) {
      this.next();
      const right = this.notExpr();
      left = { k: 'bin', op: 'and', left, right, span: join(left.span, right.span) };
    }
    return left;
  }

  private notExpr(): Ex {
    if (this.is('not')) {
      const start = this.next();
      const arg = this.notExpr();
      return { k: 'un', op: 'not', arg, span: join(start.span, arg.span) };
    }
    return this.compare();
  }

  private compare(): Ex {
    const left = this.addExpr();
    const ops: BinOp[] = ['==', '!=', '<=', '>=', '<', '>'];
    const op = ops.find((candidate) => this.is(candidate));
    if (!op || (op === '>' && this.closesSequence())) return left;
    this.next();
    const right = this.addExpr();
    return { k: 'bin', op, left, right, span: join(left.span, right.span) };
  }

  private addExpr(): Ex {
    let left = this.mulExpr();
    for (;;) {
      const op = this.is('+') ? '+' : this.is('-') ? '-' : undefined;
      if (!op) return left;
      this.next();
      const right = this.mulExpr();
      left = { k: 'bin', op, left, right, span: join(left.span, right.span) };
    }
  }

  private mulExpr(): Ex {
    let left = this.concat();
    for (;;) {
      const op = this.is('*') ? '*' : this.is('/') ? '/' : this.is('%') ? '%' : undefined;
      if (!op) return left;
      this.next();
      const right = this.concat();
      left = { k: 'bin', op, left, right, span: join(left.span, right.span) };
    }
  }

  private concat(): Ex {
    let left = this.unary();
    while (this.is('^')) {
      this.next();
      const right = this.unary();
      left = { k: 'bin', op: '^', left, right, span: join(left.span, right.span) };
    }
    return left;
  }

  private unary(): Ex {
    if (this.is('-') || this.is('#')) {
      const start = this.next();
      const arg = this.unary();
      return { k: 'un', op: start.text as '-' | '#', arg, span: join(start.span, arg.span) };
    }
    return this.postfix();
  }

  private postfix(): Ex {
    let expr = this.primary();
    for (;;) {
      if (this.is('(') && !this.peek().first) {
        this.next();
        const args: Ex[] = [];
        if (!this.is(')')) {
          do args.push(this.expr()); while (this.accept(','));
        }
        this.expect(')', 'after the arguments');
        expr = { k: 'app', fn: expr, args, span: this.span(expr.span) };
      } else if (this.is('[[')) {
        this.next();
        const pairs: Array<[Ex, Ex]> = [];
        let stmts: Stmt[] | undefined;
        do {
          const from = this.dotted();
          this.expect('<-', 'in a renaming');
          pairs.push([from, this.dotted()]);
        } while (this.accept(','));
        if (this.accept('|')) stmts = this.stmts(']]');
        this.expect(']]', 'to close the renaming');
        expr = { k: 'rename', proc: expr, pairs, ...(stmts ? { stmts } : {}), span: this.span(expr.span) };
      } else return expr;
    }
  }

  private primary(): Ex {
    const t = this.peek();
    if (t.kind === 'num') {
      this.next();
      return { k: 'num', value: Number(t.text), span: t.span };
    }
    if (t.kind === 'str' || t.kind === 'char') {
      this.next();
      return { k: 'str', value: unquote(t.text), span: t.span };
    }
    if (t.kind === 'ident') {
      if (t.text === 'true' || t.text === 'false') {
        this.next();
        return { k: 'bool', value: t.text === 'true', span: t.span };
      }
      if (t.text === 'if' || t.text === 'let') return this.lowForm();
      if (RESERVED.has(t.text)) throw new ParseError(`unexpected '${t.text}'`, t.span);
      this.next();
      // `M::Y`: a name a module exports, one name (modules are not read, so its value is unknown).
      let name = t.text;
      while (this.is('::') && this.peek(1).kind === 'ident') {
        this.next();
        name += `::${this.next().text}`;
      }
      return { k: 'name', name, span: this.span(t) };
    }
    if (t.kind !== 'op') throw new ParseError(t.kind === 'eof' ? 'this declaration ends too early' : `unexpected '${t.text}'`, t.span);
    switch (t.text) {
      case '(': {
        this.next();
        if (this.accept(')')) return { k: 'tuple', items: [], span: this.span(t) };
        const items = [this.expr()];
        while (this.accept(',')) items.push(this.expr());
        this.expect(')', 'to close the parenthesis');
        return items.length === 1 ? items[0] : { k: 'tuple', items, span: this.span(t) };
      }
      case '{': {
        this.next();
        if (this.accept('}')) return { k: 'set', items: [], span: this.span(t) };
        const first = this.dotted();
        if (this.accept('..')) {
          const to = this.is('}') ? undefined : this.dotted();
          this.expect('}', 'to close the range');
          return { k: 'range', seq: false, from: first, ...(to ? { to } : {}), span: this.span(t) };
        }
        const items = [first];
        while (this.accept(',')) items.push(this.dotted());
        if (this.accept('|')) {
          const stmts = this.stmts('}');
          this.expect('}', 'to close the set');
          return { k: 'comp', seq: false, items, stmts, span: this.span(t) };
        }
        this.expect('}', 'to close the set');
        return { k: 'set', items, span: this.span(t) };
      }
      case '{|': {
        this.next();
        const items = this.is('|}') ? [] : [this.dotted()];
        while (this.accept(',')) items.push(this.dotted());
        let stmts: Stmt[] | undefined;
        if (this.accept('|')) stmts = this.stmts('|}');
        this.expect('|}', 'to close the set of events');
        return { k: 'enum', items, ...(stmts ? { stmts } : {}), span: this.span(t) };
      }
      case '<': {
        this.next();
        this.seqDepth++;
        try {
          if (this.accept('>')) return { k: 'seq', items: [], span: this.span(t) };
          const first = this.seqItem();
          if (this.accept('..')) {
            const to = this.is('>') ? undefined : this.seqItem();
            this.expect('>', 'to close the sequence');
            return { k: 'range', seq: true, from: first, ...(to ? { to } : {}), span: this.span(t) };
          }
          const items = [first];
          while (this.accept(',')) items.push(this.seqItem());
          if (this.accept('|')) {
            const stmts = this.stmts('>');
            this.expect('>', 'to close the sequence');
            return { k: 'comp', seq: true, items, stmts, span: this.span(t) };
          }
          this.expect('>', 'to close the sequence');
          return { k: 'seq', items, span: this.span(t) };
        } finally {
          this.seqDepth--;
        }
      }
      case '[]':
      case '|~|':
      case '|||':
      case ';':
      case '||':
      case '[|':
      case '/\\':
      case '\\':
        return this.lowForm();
      default:
        throw new ParseError(`unexpected '${t.text}'`, t.span);
    }
  }

  /** A sequence item: no comparisons, so `>` closes the sequence. */
  private seqItem(): Ex {
    const first = this.addExpr();
    if (!this.is('.')) return first;
    const parts = [first];
    while (this.accept('.')) parts.push(this.addExpr());
    return { k: 'dot', parts, span: join(first.span, parts[parts.length - 1].span) };
  }
}

function join(a: Span, b: Span): Span {
  return { start: a.start, end: b.end };
}

function unquote(text: string): string {
  return text.length >= 2 ? text.slice(1, -1).replace(/\\(.)/g, '$1') : text;
}

/** The source text of a span (one line, whitespace collapsed). */
export function spanText(text: string, span: Span): string {
  return sourceText(text, span).replace(/\s+/g, ' ').trim();
}
