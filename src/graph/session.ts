/**
 * The graph side of the language server: per document version, the network
 * views built so far, one static verification report (published to the store),
 * and the layouts already computed, so a viewer refresh or an export only
 * builds and lays out what it shows. Also renders the export formats.
 *
 * Views are built on demand: the program view, the views a result is about,
 * and the first procedures in source order up to the page's budget; any other
 * view when the page opens it or an export needs it. A 1,000-procedure file
 * does not elaborate every procedure on every edit.
 */
import type * as A from '../parser/ast';
import type { CheckResult } from '../checker/checker';
import type { DeclIndex } from '../checker/index';
import type { VerificationReport } from '../verification';
import type { ViewLayout } from './layout';
import { verificationStore, type VerificationStore } from './live';
import { buildNetwork, networkViewStubs, viewProcesses, type NetworkEffectSummary, type NetworkModel, type NetworkUnit, type NetworkView, type NetworkViewStub, type ProcessTotal } from './network';
import { buildOverlays, preferredView, type OverlayModel } from './overlay';
import { buildViewerPayload, buildViewerView, DEFAULT_BUDGET, layoutOrFallback, type ViewerFocus, type ViewerPayload, type ViewerView } from './payload';
import { renderExcalidraw } from './render-excalidraw';
import { machineRequestKey, type MachineRequest, type ViewerMachine, type ViewerMachineError } from './render-machine';
import { renderViewerHtml } from './render-html';
import { formatConcurrencyMarkdown } from './render-markdown';
import { renderNetworkSvg } from './render-svg';
import { staticVerificationReport } from './static-verification';

/** What the server knows about one document's current version. */
export interface GraphDocument {
  uri: string;
  version: number;
  /** File name for titles. */
  title: string;
  text: string;
  program: A.Program;
  checked: CheckResult;
  index: DeclIndex;
  effects: ReadonlyMap<A.ProcDecl, NetworkEffectSummary>;
  /** Checker results of imported files, to expand a callee declared there. */
  unitFor?: (decl: A.ProcDecl) => NetworkUnit | undefined;
}

export type GraphFormat = 'svg' | 'excalidraw' | 'html' | 'json' | 'markdown';

/** The marker each generated file carries near its start, so a later export only overwrites its own output. */
export const GENERATOR_MARKERS: Readonly<Record<Exclude<GraphFormat, 'markdown'>, RegExp>> = Object.freeze({
  svg: /<!-- generated by processj-lsp/,
  excalidraw: /"source": "processj-lsp"/,
  html: /<meta name="generator" content="processj-lsp">/,
  json: /"generator":\s*"processj-lsp"/,
});

export const FORMAT_EXTENSIONS: Readonly<Record<Exclude<GraphFormat, 'markdown'>, string>> = Object.freeze({
  svg: '.graph.svg',
  excalidraw: '.graph.excalidraw',
  html: '.graph.html',
  json: '.graph.json',
});

export type ExportFormat = keyof typeof FORMAT_EXTENSIONS;

/** Whether `name` is an export format (its own key, not one inherited from Object). */
export function isExportFormat(name: string): name is ExportFormat {
  return Object.hasOwn(FORMAT_EXTENSIONS, name);
}

/** What `all` writes: the pictures and the page. JSON is for tools, and large on a big program: ask for it by name. */
export const ALL_FORMATS: readonly ExportFormat[] = Object.freeze(['svg', 'excalidraw', 'html']);

/** How many views a self-contained page carries. */
const FILE_BUDGET = Object.freeze({ views: 200, nodes: 15_000 });

/** How many state machines a self-contained page carries (it cannot ask for more). */
const FILE_MACHINES = 40;

/**
 * The state machine a page asks for (src/graph/render-machine.ts), from the
 * CSP model of the request's target; the language server provides it.
 */
export type MachineProvider = (document: GraphDocument, request: MachineRequest) => Promise<ViewerMachine | ViewerMachineError | undefined>;

interface Entry {
  version: number;
  /** Every view of the document, in display order. */
  stubs: NetworkViewStub[];
  /** Views built so far, by id. */
  built: Map<string, NetworkView>;
  defaultView: string;
  staticReport: VerificationReport;
  layouts: Map<string, ViewLayout>;
}

export class GraphSession {
  private readonly entries = new Map<string, Entry>();

  constructor(private readonly store: VerificationStore = verificationStore, private readonly serverVersion?: string, private readonly machines?: MachineProvider) {}

  /** The views and static report of this version, computed once; the static report is published. */
  entry(document: GraphDocument): Entry {
    const cached = this.entries.get(document.uri);
    if (cached && cached.version === document.version) return cached;
    const stubs = networkViewStubs(document.program, document.uri);
    const entry: Entry = { version: document.version, stubs, built: new Map(), defaultView: stubs[0]?.id ?? '', staticReport: undefined!, layouts: new Map() };
    // The checker's proofs name processes as the views of their procedures draw them.
    const owners = new Set<string>();
    for (const fact of document.checked.deadlocks) {
      const owner = document.program.decls.find((decl): decl is A.ProcDecl => decl.kind === 'ProcDecl' && !!decl.body && inside(decl.span, fact.par.span));
      if (owner) owners.add(owner.name.name);
    }
    for (const fact of document.checked.channels) if (fact.hazard) owners.add(fact.procedure.name.name);
    this.ensure(document, entry, [...owners].map((name) => this.stubsNamed(entry, name)).flat().map((stub) => stub.id));
    if (!stubs.some((stub) => stub.kind === 'program')) {
      // No main: open on the first procedure that communicates, building views a batch at a time.
      for (let start = 0; start < stubs.length; start += 40) {
        const batch = stubs.slice(start, start + 40);
        this.ensure(document, entry, batch.map((stub) => stub.id));
        const talking = batch.find((stub) => entry.built.get(stub.id)?.edges.length);
        if (talking) {
          entry.defaultView = talking.id;
          break;
        }
      }
    }
    entry.staticReport = staticVerificationReport(document.program, document.checked, { uri: document.uri, documentVersion: document.version, model: this.model(document, entry), version: this.serverVersion });
    this.entries.set(document.uri, entry);
    this.store.publish(document.uri, entry.staticReport);
    return entry;
  }

  /** Every result for the document: FDR first, then the checker's report for this version. */
  reports(document: GraphDocument): VerificationReport[] {
    const entry = this.entry(document);
    return [...this.store.get(document.uri).filter((report) => report.producer !== 'checker'), entry.staticReport];
  }

  /** The model with the views built so far (and, when asked, these too). */
  model(document: GraphDocument, entry = this.entry(document), ids: readonly string[] = []): NetworkModel {
    this.ensure(document, entry, ids);
    return {
      version: 1,
      generator: 'processj-lsp',
      uri: document.uri,
      title: document.title,
      views: entry.stubs.map((stub) => entry.built.get(stub.id)).filter((view): view is NetworkView => !!view),
      defaultView: entry.defaultView,
    };
  }

  async payload(document: GraphDocument, budget: { views: number; nodes: number } = DEFAULT_BUDGET, focus?: ViewerFocus): Promise<ViewerPayload> {
    const entry = this.entry(document);
    const reports = this.reports(document);
    // The default view, every view a result is about, then procedures in source order up to the budget.
    const wanted = new Set([entry.defaultView, ...this.resultViews(entry, reports)]);
    for (const stub of entry.stubs) {
      if (wanted.size >= budget.views) break;
      wanted.add(stub.id);
    }
    return buildViewerPayload({
      model: this.model(document, entry, [...wanted]),
      stubs: entry.stubs,
      reports,
      source: { uri: document.uri, text: document.text },
      documentVersion: document.version,
      layouts: entry.layouts,
      onLayout: (view, layout) => entry.layouts.set(view.id, layout),
      budget,
      focus,
    });
  }

  /** One state machine, for a page that asks (the live page, VS Code's panel). */
  async machine(document: GraphDocument, request: MachineRequest): Promise<ViewerMachine | ViewerMachineError | undefined> {
    return this.machines?.(document, request);
  }

  /** One view the page asked for (one the payload sent as pending), with the URIs it links to. */
  async view(document: GraphDocument, id: string): Promise<ViewerView | undefined> {
    const entry = this.entry(document);
    const model = this.model(document, entry, [id]);
    const view = entry.built.get(id);
    if (!view) return undefined;
    const known = new Set<string>([document.uri]);
    return { ...buildViewerView(model, view, await this.layout(document, view), known), knownUris: [...known].sort() };
  }

  async layout(document: GraphDocument, view: NetworkView): Promise<ViewLayout> {
    const entry = this.entry(document);
    let layout = entry.layouts.get(view.id);
    if (!layout) {
      layout = await layoutOrFallback(view);
      entry.layouts.set(view.id, layout);
    }
    return layout;
  }

  /**
   * The picture worth exporting: the view where the most important failure is
   * placed (FDR before the checker, errors before warnings), with its end state,
   * or the default view when nothing failed. Undefined when there is nothing to draw.
   */
  focus(document: GraphDocument): { view: NetworkView; overlay?: OverlayModel } | undefined {
    const entry = this.entry(document);
    const reports = this.reports(document);
    const model = this.model(document, entry, [entry.defaultView, ...this.resultViews(entry, reports)]);
    const overlays = buildOverlays(model, reports, { documentVersion: document.version });
    const rank = (severity: string): number => severity === 'error' ? 0 : severity === 'warning' ? 1 : 2;
    const failures = reports.flatMap((report, index) => report.checks.filter((check) => check.status === 'failed' && check.counterexample).map((check) => ({ index, check })))
      .sort((a, b) => rank(a.check.severity) - rank(b.check.severity));
    for (const failure of failures) {
      const viewId = preferredView(model, failure.check, overlays, failure.index);
      const overlay = overlays.find((entry) => entry.view === viewId && entry.report === failure.index && entry.check === failure.check.id);
      const view = model.views.find((candidate) => candidate.id === viewId);
      if (view && overlay) return { view, overlay };
    }
    const view = model.views.find((candidate) => candidate.id === entry.defaultView) ?? model.views[0];
    return view ? { view } : undefined;
  }

  /** The processes the program view draws (undefined without a main): what a model of the whole program has to hold. */
  programProcesses(document: GraphDocument): ProcessTotal | undefined {
    const entry = this.entry(document);
    const stub = entry.stubs.find((candidate) => candidate.kind === 'program');
    if (!stub) return undefined;
    const view = this.model(document, entry, [stub.id]).views.find((candidate) => candidate.id === stub.id);
    return view ? viewProcesses(view) : undefined;
  }

  /** Whether the document has a procedure with a body to draw. */
  drawable(document: GraphDocument): boolean {
    return this.entry(document).stubs.length > 0;
  }

  async render(document: GraphDocument, format: GraphFormat, options: { nonce?: string; focus?: ViewerFocus } = {}): Promise<string> {
    const entry = this.entry(document);
    if (format === 'markdown') return formatConcurrencyMarkdown(document.title, this.model(document, entry, entry.stubs.map((stub) => stub.id)), this.reports(document));
    // A file cannot ask for more views or state machines later, so it carries more of them.
    if (format === 'html') {
      const payload = await this.payload(document, FILE_BUDGET, options.focus);
      const machines = await this.fileMachines(document, payload);
      return renderViewerHtml(machines ? { ...payload, machines } : payload, { mode: 'file', nonce: options.nonce });
    }
    if (format === 'json') {
      const model = this.model(document, entry, entry.stubs.map((stub) => stub.id));
      // Compact: a large program's model is tens of megabytes pretty-printed.
      return `${JSON.stringify({ generator: 'processj-lsp', version: 1, title: document.title, uri: document.uri, documentVersion: document.version, model, layouts: Object.fromEntries(entry.layouts), reports: this.reports(document) })}\n`;
    }
    const focus = this.focus(document);
    if (!focus) throw new Error('this file has no procedure with a body to draw');
    const layout = await this.layout(document, focus.view);
    return format === 'svg'
      ? renderNetworkSvg(focus.view, layout, { title: document.title, overlay: focus.overlay })
      : renderExcalidraw(focus.view, layout, { title: document.title, overlay: focus.overlay });
  }

  forget(uri: string): void {
    this.entries.delete(uri);
  }

  /**
   * The state machines a file page can show without asking: those of the
   * processes FDR's results are about (with their trails), then of every
   * process the results' views and the default view draw, up to a budget.
   * The requests are the ones the page makes (viewer.ts machineRequest).
   */
  private async fileMachines(document: GraphDocument, payload: ViewerPayload): Promise<Record<string, ViewerMachine | ViewerMachineError> | undefined> {
    if (!this.machines) return undefined;
    const requests = new Map<string, MachineRequest>();
    const add = (request: MachineRequest): void => {
      if (requests.size < FILE_MACHINES) requests.set(machineRequestKey(request), request);
    };
    for (const overlay of payload.overlays) {
      const chip = payload.chips.find((entry) => entry.report === overlay.report && entry.check === overlay.check);
      const view = payload.views.find((entry) => entry.id === overlay.view);
      if (overlay.producer !== 'fdr' || !chip || !view) continue;
      for (const process of overlay.processes) {
        const ref = view.nodes.find((node) => node.id === process.node)?.machine;
        if (ref && process.trail) add({ target: chip.target, ref, check: overlay.check, process: process.key });
      }
      for (const node of view.nodes) if (node.machine) add({ target: chip.target, ref: node.machine });
    }
    const first = payload.views.find((view) => view.id === payload.defaultView);
    for (const view of [...(first ? [first] : []), ...payload.views]) {
      if (view.pending) continue;
      for (const node of view.nodes) if (node.machine) add({ target: view.target, ref: node.machine });
    }
    const out: Record<string, ViewerMachine | ViewerMachineError> = {};
    for (const [key, request] of requests) {
      const machine = await this.machines(document, request);
      if (machine) out[key] = machine;
    }
    return out;
  }

  /** Build the views with these ids that are not built yet. */
  private ensure(document: GraphDocument, entry: Entry, ids: readonly string[]): void {
    const missing = entry.stubs.filter((stub) => ids.includes(stub.id) && !entry.built.has(stub.id));
    if (!missing.length) return;
    const model = buildNetwork(document.program, document.checked, {
      uri: document.uri,
      text: document.text,
      title: document.title,
      effects: document.effects,
      index: document.index,
      unitFor: document.unitFor,
      only: [...new Set(missing.map((stub) => stub.kind === 'program' ? 'program' : stub.procedure))],
    });
    for (const view of model.views) if (!entry.built.has(view.id)) entry.built.set(view.id, view);
  }

  private stubsNamed(entry: Entry, name: string): NetworkViewStub[] {
    return entry.stubs.filter((stub) => stub.procedure === name);
  }

  /** Views a result may be placed in: the program view (it expands procedures in place) and each target's own view. */
  private resultViews(entry: Entry, reports: readonly VerificationReport[]): string[] {
    const ids = new Set<string>();
    for (const report of reports) {
      for (const check of report.checks) {
        if (!check.counterexample) continue;
        for (const stub of entry.stubs) {
          if (stub.kind === 'program' || (check.target.kind === 'procedure' && stub.procedure === check.target.name)) ids.add(stub.id);
        }
      }
    }
    return [...ids];
  }
}

function inside(outer: A.Span, inner: A.Span): boolean {
  const before = (a: A.Pos, b: A.Pos): boolean => a.line < b.line || (a.line === b.line && a.col <= b.col);
  return before(outer.start, inner.start) && before(inner.end, outer.end);
}
