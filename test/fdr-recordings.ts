/**
 * refines output recorded for the tests (test/fixtures/fdr/<name>.json), so
 * the tests that explain or draw FDR's answers run without FDR. Each recording
 * names a hash of the model it was made for: when the translator generates
 * something else, the tests say so, and the recordings are made again with FDR
 * installed:
 *
 *   PJ_RECORD_FDR=1 npm test
 *
 * Recordings use one BFS worker, so refines finds the same deadlock and
 * runtime-error counterexamples every time (a termination or determinism
 * counterexample can still differ, so the tests that compare with a live run
 * leave those out).
 */
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { findRefines, runRefines, type CspModel, type FdrResult, type FdrRun } from '../src/csp/index';

export const FDR_FIXTURES = path.join(__dirname, '..', '..', 'test', 'fixtures', 'fdr');
export const refines = findRefines();
const RECORD = process.env.PJ_RECORD_FDR === '1' && !!refines;

/** The model a recording was made for: a recording of another model explains nothing. */
export function modelHash(model: CspModel): string {
  // The header names the file the program was loaded from; the rest is the model.
  return createHash('sha256').update(model.text.replace(/^-- Generated by processj-lsp from [^\n]*\n/, '')).digest('hex').slice(0, 16);
}

/** refines' output for a model: recorded under `name`, or recorded afresh with PJ_RECORD_FDR=1. */
export async function recordedRun(name: string, model: CspModel): Promise<FdrRun> {
  const file = path.join(FDR_FIXTURES, `${name}.json`);
  if (RECORD) {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pj-fdr-record-'));
    try {
      const csp = path.join(dir, `${name}.csp`);
      fs.writeFileSync(csp, model.text);
      const run = await runRefines(refines!, csp, { timeoutMs: 60_000, workers: 1 });
      assert.deepEqual(run.errors, [], `${name}: FDR accepts the model`);
      const kept = { model: modelHash(model), version: run.version, results: run.results.map(({ ms: _ms, ...r }) => r), eventMap: run.eventMap, errors: run.errors, warnings: run.warnings };
      fs.mkdirSync(FDR_FIXTURES, { recursive: true });
      fs.writeFileSync(file, `${JSON.stringify(kept)}\n`);
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  }
  const raw = JSON.parse(fs.readFileSync(file, 'utf8')) as Pick<FdrRun, 'version' | 'results' | 'eventMap' | 'errors' | 'warnings'> & { model?: string };
  assert.equal(raw.model, modelHash(model), `${name}: test/fixtures/fdr/${name}.json was recorded for another model; re-record with PJ_RECORD_FDR=1 npm test`);
  return { ...raw, timedOut: false, aborted: false, exitCode: 0, durationMs: 0, stderr: '' };
}

/** The output recorded for a model, as refines prints it: one framed JSON object (the replaying refines below prints this too). */
export function framedRecording(recorded: { version?: string; results: Array<Omit<FdrResult, 'ms'>>; eventMap: Record<string, string>; errors: string[]; warnings: string[] }, name: string): Record<string, unknown> {
  const results = recorded.results.map((r) => ({ assertion_string: r.assertion, result: r.passed === true ? 1 : r.passed === false ? 0 : 2, is_negated: r.negated ? 1 : 0, errors: r.errors, visited_states: r.states, visited_transitions: r.transitions, counterexamples: r.counterexamples }));
  return { copyright_notice: 'FDR Version ' + recorded.version + ' (replayed from ' + name + ')', results, event_map: recorded.eventMap, errors: recorded.errors, warnings: recorded.warnings };
}

/**
 * What a runner answers processj/runRefines with for a model text (its frames,
 * one per line refines printed), from the recordings: so the browser build's
 * FDR features run in tests without FDR or a runner.
 */
export function recordedFrames(text: string): { exitCode: number; frames: unknown[] } {
  const hash = createHash('sha256').update(text.replace(/^-- Generated by processj-lsp from [^\n]*\n/, '')).digest('hex').slice(0, 16);
  for (const entry of fs.readdirSync(FDR_FIXTURES).filter((file) => file.endsWith('.json')).sort()) {
    const recorded = JSON.parse(fs.readFileSync(path.join(FDR_FIXTURES, entry), 'utf8'));
    if (recorded.model === hash) return { exitCode: 0, frames: [framedRecording(recorded, entry)] };
  }
  return { exitCode: 1, frames: [{ errors: [`no recording of this model (${hash})`], results: [] }] };
}

/**
 * A stand-in for refines that answers from the recordings: for the model it
 * is given it prints, as refines' framed JSON, the output recorded for that
 * model, so the server's FDR features run in tests without FDR. A model with
 * no recording gets a file-level error. Returns the executable's path.
 */
export function replayingRefines(dir: string): string {
  const script = path.join(dir, 'refines.js');
  fs.writeFileSync(script, `'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const framedRecording = ${framedRecording.toString()};
const file = process.argv[process.argv.length - 1];
const text = fs.readFileSync(path.resolve(process.cwd(), file), 'utf8');
const hash = createHash('sha256').update(text.replace(/^-- Generated by processj-lsp from [^\\n]*\\n/, '')).digest('hex').slice(0, 16);
const dir = ${JSON.stringify(FDR_FIXTURES)};
const name = fs.readdirSync(dir).filter((entry) => entry.endsWith('.json')).find((entry) => JSON.parse(fs.readFileSync(path.join(dir, entry), 'utf8')).model === hash);
if (name) {
  const recorded = JSON.parse(fs.readFileSync(path.join(dir, name), 'utf8'));
  process.stdout.write(JSON.stringify(framedRecording(recorded, name)) + '\\n');
} else {
  process.stdout.write(JSON.stringify({ errors: ['no recording of this model (' + hash + ')'], results: [] }) + '\\n');
  process.exitCode = 1;
}
`);
  const wrapper = path.join(dir, 'refines');
  fs.writeFileSync(wrapper, `#!/bin/sh\nexec ${JSON.stringify(process.execPath)} ${JSON.stringify(script)} "$@"\n`);
  fs.chmodSync(wrapper, 0o755);
  return wrapper;
}

/** A program whose process runs a procedure of another file (lib/workers.pj): its model reads both files (recorded as `imported`). */
export const IMPORTED: Readonly<Record<string, string>> = Object.freeze({
  'uses_lib.pj': ['import lib.workers;', '', 'public void main(string[] args) {', '    chan<int> c;', '    par {', '        writer2(c.write);', '        { int x = c.read(); }', '    }', '}', ''].join('\n'),
  'lib/workers.pj': ['public void writer2(chan<int>.write out) {', '    out.write(1);', '    out.write(2);', '}', ''].join('\n'),
});
