function assertIdentities(file: string, text?: string): CspModel {
  const loaded = load(file, text);
  const m = translateProgram({ units: loaded.units, index: loaded.index });
  const root = loaded.units[0].program.decls.find((d): d is A.ProcDecl => d.kind === 'ProcDecl' && d.name.name === 'main')!;
  const expected = expectedPaths(loaded.units, root);
  const actual = m.sourceMap.processes.filter((p) => p.process).map((p) => p.process!.path);
  const missing = expected.filter((e) => !actual.some((a) => samePath(a, e)));
  const extra = actual.filter((a) => !expected.some((e) => samePath(a, e)));
  assert.deepEqual({ missing: missing.map(pathText), extra: extra.map(pathText) }, { missing: [], extra: [] }, path.basename(file));
  assert.equal(actual.length, expected.length, `${path.basename(file)}: one process per path`);
  return m;
}

