test('miscompilations no lint reports are named with the model, where they are', () => {
  const differential = (name: string): CspModel => {
    const file = path.join(ROOT, 'test', 'differential', name);
    const loaded = load(file);
    return translateProgram({ units: loaded.units, index: loaded.index });
  };
  const codes = (m: CspModel): string[] => m.warnings.filter((w) => w.code?.startsWith('compiler/')).map((w) => `${w.at!.span.start.line + 1}:${w.code}`);
  // A break or continue after a nested for, par for or do loop jumps to the inner loop's exit in this build.
  assert.deepEqual(codes(differential('main_break_after_for.pj')), ['9:compiler/loop-labels']);
  assert.deepEqual(codes(differential('break_after_par_for.pj')), ['8:compiler/loop-labels']);
  assert.deepEqual(codes(differential('continue_after_nested_for.pj')), ['10:compiler/loop-labels']);
  // A while restores the labels; a break before the nested loop, in a switch or in a plain method is fine.
  for (const fine of ['break_after_nested_while.pj', 'break_before_nested_for.pj', 'switch_break_after_for.pj', 'break_after_for_nonyield.pj', 'breaks_that_work.pj']) {
    assert.deepEqual(codes(differential(fine)), [], fine);
  }
  // A par branch that loops over calls of a suspending procedure can end the par early; a par for is counted right.
  const loopCalls = differential('par_loop_of_calls.pj');
  assert.deepEqual(codes(loopCalls), ['7:compiler/par-loop-calls']);
  assert.match(loopCalls.warnings.find((w) => w.code === 'compiler/par-loop-calls')!.message, / — this ProcessJ build counts those calls against the wrong par/);
  const parFor = program([
    'import std.*;',
    'public void worker(int i, shared chan<int>.write out) { out.write(i); }',
    'public void main(string[] args) {',
    '    shared chan<int> c;',
    '    par {',
    '        par for (int i = 0; i < 3; i++) worker(i, c.write);',
    '        for (int j = 0; j < 3; j++) println("got " + c.read());',
    '    }',
    '}',
  ].join('\n'));
  assert.deepEqual(codes(parFor), []);
});

