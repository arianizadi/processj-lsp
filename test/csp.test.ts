test('an integer that never decides anything is saturated instead of range-checked', () => {
  const source = (reader: string): string => [
    '//@csp int 0..3',
    'import std.*;',
    'public void main(string[] args) {',
    '    chan<int> c;',
    '    chan<int> d;',
    `    par { { int v = c.read(); v = v + 2; d.write(v * v); } { c.write(2); ${reader} } }`,
    '}',
  ].join('\n');
  // The reader only prints what it gets: no value of c or d can change what happens.
  const m = program(source('int w = d.read(); println(w);'));
  assert.deepEqual(m.unsupported, []);
  assert.deepEqual(Object.values(m.sourceMap.errors).filter((e) => e.kind === 'range'), []);
  assert.match(m.text, /\nPJ_SAT = 4\nInt_s = \{0\.\.4\}\n/);
  assert.match(m.text, /\nchannel c : Int_s\nchannel d : Int_s\n/);
  // v + 2 is kept while it fits; anything computed from a saturated v stays saturated.
  assert.match(m.text, /pj_satv\(v \+ 2, \{v\}\)/);
  assert.match(m.text, /d!pj_satv\(v \* v, \{v\}\)/);
  assert.ok(m.assumptions.some((a) => /never decide anything/.test(a) && /channels c, d/.test(a)), m.assumptions.join('\n'));
  // Once the reader's value decides a branch, every value it depends on is exact again.
  const exact = program(source('int w = d.read(); if (w > 1) println(w);'));
  assert.ok(Object.values(exact.sourceMap.errors).some((e) => e.kind === 'range' && e.at.span.start.line === 5));
  assert.doesNotMatch(exact.text, /PJ_SAT/);
  // A user's specification that names a channel sees its exact values.
  const spec = program(`//@csp assert MAIN [T= MAIN\n/*@csp\nD_SPEC = d?x -> D_SPEC\n*/\n${source('int w = d.read(); println(w);')}`);
  assert.match(spec.text, /\nchannel d : Int_t\n/);
  // A checked procedure's channels are seen by its caller: exact.
  const proc = procedure(['public void twice(chan<int>.read in, chan<int>.write out) {', '    int v = in.read();', '    out.write(v * 2);', '}', 'public void main(string[] args) { }'].join('\n'), 'twice');
  assert.doesNotMatch(proc.text, /PJ_SAT/);
  assert.ok(Object.values(proc.sourceMap.errors).some((e) => e.kind === 'range'));
});

