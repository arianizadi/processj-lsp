const PIPELINE = [
  'import std.*;',
  'public void producer(chan<int>.write out) { for (int i = 1; i <= 3; i++) out.write(i); }',
  'public void consumer(chan<int>.read in) {',
  '    int sum = 0;',
  '    for (int i = 0; i < 3; i++) sum = sum + in.read();',
  '    println(sum);',
  '}',
  'public void main(string[] args) {',
  '    chan<int> a;',
  '    par {',
  '        producer(a.write);',
  '        consumer(a.read);',
  '    }',
  '}',
].join('\n');

test('a program becomes procedures, one slot per par branch, a network and the standard checks', () => {
  const m = program(PIPELINE);
  assert.deepEqual(m.unsupported, []);
  assert.equal(m.root, 'MAIN');
  assert.match(m.text, /^-- Generated by processj-lsp from test\.pj\. Regenerated by Convert to CSP and by Check with FDR; edit the ProcessJ source, not this file\./);
  // The consumer only adds up and prints what it reads: a's values never decide anything (saturated, Int_s).
  assert.match(m.text, /\nchannel a : Int_s\n/);
  assert.match(m.text, /\nproducer__body\(out, pj_k\) = /);
  // One fork event starts both branches; a slot never terminates (the program ends on main's pj_end).
  assert.match(m.text, /\nmain__par10_1\(pj_h\) = \(pj_fork_main_10\.pj_h -> producer__body\(a, main__par10_1__end\(pj_h\)\)\) \[\] \(pj_end -> STOP\)/);
  assert.match(m.text, /\nmain__10\(pj_h, pj_k\) = pj_fork_main_10\.pj_h -> main__10_join1\(pj_h, pj_k\)\n/);
  assert.match(m.text, /\nMAIN = \(\(PJ_NET \[\| \{pj_end\} \|> SKIP\) \\ PJ_HIDDEN\)\n/);
  // No process of the network ends in SKIP (FDR's distributed termination over n of them costs 2^n).
  const networkLines = m.text.split('\n').filter((l) => /^(PJ_NET|main__par|PJ_BAR|PJ_MED)/.test(l) || /\[\] pj_end ->/.test(l));
  assert.ok(networkLines.length && networkLines.every((l) => !/SKIP/.test(l)), networkLines.join('\n'));
  assert.deepEqual(m.assertions.map((a) => [a.id, a.property, a.severity]), [
    ['deadlock-free', 'deadlock-free', 'error'],
    ['no-runtime-errors', 'no-runtime-errors', 'error'],
    ['terminates', 'terminates', 'info'],
  ]);
  assert.match(m.text, /\nassert PJ_NOERR\(MAIN\) :\[deadlock free \[F\]\]\n/);
  // The write is a named definition that knows its statement.
  const write = Object.values(m.sourceMap.definitions).find((d) => d.operation?.kind === 'write');
  assert.ok(write);
  assert.equal(write.procedure, 'producer');
  assert.equal(write.operation?.channel, 'out');
  assert.equal(write.at?.span.start.line, 1);
  // One leaf per process: main and its two branches.
  assert.deepEqual(m.sourceMap.processes.map((p) => p.kind), ['root', 'branch', 'branch']);
  assert.deepEqual(m.sourceMap.processes.map((p) => p.process?.label), ['main', 'producer(a.write)', 'consumer(a.read)']);
  assert.equal(m.sourceMap.channels.a.ref?.declaration?.span.start.line, 8);
  assert.equal(m.sourceMap.channels.a.hidden, false);
});

test('straight-line code folds into the next definition and dead variables are never parameters', () => {
  const m = program([
    'public void main(string[] args) {',
    '    chan<int> c;',
    '    int unused = 3;',
    '    int x = 1;',
    '    x = x + 1;',
    '    par { c.write(x * 2); { int y = c.read(); } }',
    '}',
  ].join('\n'));
  assert.deepEqual(m.unsupported, []);
  // x = 1; x = x + 1 is folded into the par's argument; `unused` and `y` are never parameters.
  assert.match(m.text, /\nmain__body\(pj_h, pj_k\) = main__6\(pj_h, 2, pj_k\)\n/);
  assert.match(m.text, /\nmain__6\(pj_h, x, pj_k\) = pj_fork_main_6\.pj_h!x -> /);
  // The fork carries what any branch needs; a branch that needs nothing ignores it.
  assert.match(m.text, /\nmain__par6_2\(pj_h\) = \(pj_fork_main_6\.pj_h\?_:pj_forkset_main_6\(pj_h\) -> /);
  assert.doesNotMatch(m.text, /\(.*\bunused\b.*\) =/);
  assert.match(m.text, /= c\?y -> main__par6_2__end/);
});

