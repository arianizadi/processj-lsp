function load(file: string, text?: string) {
  const loaded = loadProgram(file, INCLUDE, text);
  assert.deepEqual(loaded.syntaxErrors, [], `${path.basename(file)} must parse`);
  return loaded;
}

function program(text: string, name = 'test.pj'): CspModel {
  const loaded = load(path.join(os.tmpdir(), name), text);
  return translateProgram({ units: loaded.units, index: loaded.index });
}

function procedure(text: string, proc: string): CspModel {
  const loaded = load(path.join(os.tmpdir(), 'proc.pj'), text);
  return translateProcedure({ units: loaded.units, index: loaded.index }, proc);
}

